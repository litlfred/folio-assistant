/**
 * Write input/pagecontent/personas.md from scenarios/roles.json and
 * scenarios/actors/*.json, so the personas are kept once, in their actors.
 * Every person is fictional.
 *
 *   bun tools/personas/gen_personas.ts          (write)
 *   bun tools/personas/gen_personas.ts --check  (fail if the page is stale)
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

type Role = { id: string; title: string; description: string; actorKinds: string[] };
type Persona = { name: string; role: string; goal: string; needs: string[]; frustrations: string[] };
type Actor = { id: string; title: string; kind: string; description: string; roles: string[]; meta?: { persona?: Persona } };

const root = resolve(import.meta.dir, "..", "..");
const out = join(root, "input", "pagecontent", "personas.md");
const roles: Role[] = JSON.parse(readFileSync(join(root, "scenarios", "roles.json"), "utf-8")).roles;
const dir = join(root, "scenarios", "actors");
const actors: Actor[] = readdirSync(dir)
  .filter((f) => f.endsWith(".json"))
  .sort()
  .map((f) => JSON.parse(readFileSync(join(dir, f), "utf-8")));
const roleTitle = new Map(roles.map((r) => [r.id, r.title]));
const cell = (s: string) => s.replace(/\|/g, "\\|");
const titles = (ids: string[]) => ids.map((id) => roleTitle.get(id) ?? id).join(", ");

const lines: string[] = [
  "<!-- Generated by tools/personas/gen_personas.ts from scenarios/roles.json and scenarios/actors/ — do not edit; change those and regenerate. -->",
  "",
  "This page lists the roles the business processes of this guide name, and the example people and systems that play them. Every person is fictional.",
  "",
  "### Roles",
  "",
  "| Role | Played by | Description |",
  "| --- | --- | --- |",
  ...roles.map((r) => `| ${cell(r.title)} | ${r.actorKinds.join(", ")} | ${cell(r.description)} |`),
  "",
  "### Example people",
  "",
];
for (const a of actors.filter((x) => x.kind === "person")) {
  const p = a.meta?.persona;
  lines.push(`#### ${a.title}`, "", a.description, "", `Roles: ${titles(a.roles)}.`, "");
  if (p) {
    lines.push(`**Goal.** ${p.goal}`, "", "**Needs**", "", ...p.needs.map((n) => `- ${n}`), "", "**Frustrations**", "", ...p.frustrations.map((n) => `- ${n}`), "");
  }
}
lines.push("### Example systems", "", "| System | Roles | Description |", "| --- | --- | --- |");
for (const a of actors.filter((x) => x.kind === "system")) lines.push(`| ${cell(a.title)} | ${titles(a.roles)} | ${cell(a.description)} |`);
lines.push("");
const text = lines.join("\n");

if (process.argv.includes("--check")) {
  const prev = existsSync(out) ? readFileSync(out, "utf-8") : "";
  if (prev !== text) {
    console.error("✗ input/pagecontent/personas.md is stale: run bun tools/personas/gen_personas.ts");
    process.exit(1);
  }
  console.log("✓ input/pagecontent/personas.md up to date");
} else {
  writeFileSync(out, text);
  console.log("✓ input/pagecontent/personas.md");
}
