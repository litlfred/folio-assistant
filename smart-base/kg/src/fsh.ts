export interface FshFile {
  /** Path relative to the smart-base repository root. */
  path: string;
  text: string;
}

export function fshFiles(layer: LayerSpec, source: string): FshFile[] {
  const banner = GENERATED_BANNER(source);
  // derivation belongs to the document envelope, so only the base layer emits it.
  const base = !layer.imports?.length;
  const lists = [...(base ? [DERIVATION] : []), ...layer.valueSets.map((v) => codeListOf(v, layer.layer.toUpperCase())), ...layerCodeLists(layer)];
  const files: FshFile[] = [];
  for (const l of lists) {
    files.push({ path: `input/fsh/codesystems/${l.name}.fsh`, text: `${banner}\n${codeSystem(l)}\n` });
    files.push({ path: `input/fsh/valuesets/${l.name}VS.fsh`, text: `${banner}\n${valueSet(l)}\n` });
  }
  const models = [...layer.classes.map((c) => classModel(c, layer)), ...(base ? [envelopeModels(layer)] : [])].join("\n\n");
  files.push({ path: `input/fsh/models/KG${pascal(layer.layer).toUpperCase().replace("LIBRARY", "Library")}.fsh`, text: `${banner}\n${models}\n` });
  return files;
}
