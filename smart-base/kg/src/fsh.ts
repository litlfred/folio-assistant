/**
 * FHIR Shorthand generated from the Zod schema — the bridge to the FHIR
 * toolchain.
 *
 * SUSHI compiles what this writes into StructureDefinitions (logical models),
 * CodeSystems and ValueSets; the IG Publisher renders them; and smart-base's
 * existing `input/scripts/generate_logical_model_schemas.py` and
 * `generate_valueset_schemas.py` turn those into JSON Schema and JSON-LD, as
 * they already do for every other logical model here. Nothing downstream needs
 * to know the source was Zod.
 *
 * What is generated:
 *  - one CodeSystem `<Name>` + all-codes ValueSet `<Name>VS` per closed code
 *    list (`vocab.ts`) — the `VS` suffix as `CoreDataElementTypeVS` has it,
 *    since SUSHI warns when the two share a name —
 *    plus one each for the layer's class ids and predicates;
 *  - one Logical model per ontology class, `KG<Class>`, whose elements are the
 *    class's typed properties — the instance shape a node's `definedBy`
 *    points at;
 *  - the document envelope: `KGGraphDocument`, `KGNode`, `KGEdge`,
 *    `KGEvidenceLocation`, `KGProvenanceSource` (not `KGEvidence`: that is the
 *    L1 class `evidence`, a body of evidence, not a pointer into a source).
 *
 * One deliberate difference from the JSON: FHIR element names cannot start
 * with `@`, so the document's `@context` is the element `context`. The JSON
 * Schema emitted from Zod keeps `@context`, and is the one a JSON document is
 * validated against.
 */
import { bindingOf, type ClassSpec, type LayerSpec, type PropertySpec } from "./ontology.ts";
import { codeListOf, DERIVATION, pascal, type CodeList } from "./vocab.ts";

export { pascal };

export const GENERATED_BANNER = (source: string) =>
  `// GENERATED by smart-base/kg/src/emit.ts from ${source}. Do not edit: change the Zod source and run \`npm run build\` in smart-base/kg/.`;

/** A FSH string literal. */
export function q(s: string): string {
  return `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\s*\n\s*/g, " ")}"`;
}

export function classModelName(c: ClassSpec): string {
  return `KG${pascal(c.id)}`;
}

function codeSystem(l: CodeList): string {
  const out = [
    `CodeSystem: ${l.name}`,
    `Title: ${q(l.title)}`,
    `Description: ${q(`${l.description} Source: ${l.source}.`)}`,
    "",
    "* ^experimental = false",
    "* ^caseSensitive = true",
    "* ^status = #active",
    '* ^publisher = "World Health Organization (WHO)"',
    "",
    ...l.codes.map((c) => `* #${c.code} ${q(c.display)} ${q(c.definition)}`),
  ];
  return out.join("\n");
}

function valueSet(l: CodeList): string {
  return [
    `ValueSet: ${l.name}VS`,
    `Title: ${q(l.title)}`,
    `Description: ${q(`All codes of ${l.name}.`)}`,
    "",
    "* ^experimental = false",
    "* ^status = #active",
    '* ^publisher = "World Health Organization (WHO)"',
    `* include codes from system ${l.name}`,
  ].join("\n");
}

/** The layer's own vocabularies: its class ids and its predicates. */
export function layerCodeLists(l: LayerSpec): CodeList[] {
  const tag = pascal(l.layer).toUpperCase().replace("LIBRARY", "Library");
  return [
    {
      name: `KG${tag}Classes`,
      title: `Knowledge graph ${tag}: classes`,
      description: `The classes of the ${tag} layer of the SMART Guidelines knowledge graph. A node's \`type\` is one of these.`,
      source: `smart-base/kg/src/${l.layer}.ts (migrated from smart-kg ontology/${l.layer}/${l.layer}.json)`,
      codes: l.classes.map((c) => ({ code: c.id, display: c.name, definition: c.note })),
    },
    {
      name: `KG${tag}Predicates`,
      title: `Knowledge graph ${tag}: predicates`,
      description: `The predicates of the ${tag} layer. An edge's \`predicate\` is one of these; which (source, target) pairs each licenses is the layer's edge table.`,
      source: `smart-base/kg/src/${l.layer}.ts (migrated from smart-kg ontology/${l.layer}/${l.layer}.json)`,
      codes: l.predicates.map((p) => ({ code: p.predicate, display: p.predicate, definition: p.note })),
    },
  ];
}

/** The FSH binding strength for a smart-kg binding: an error is required, a warning extensible. */
const strength = (c: ClassSpec, prop: string): string =>
  bindingOf(c.valueSets?.[prop] ?? "x").severity === "warning" ? "extensible" : "required";

function elementLines(name: string, p: PropertySpec, c: ClassSpec, indent = ""): string[] {
  const out = [`${indent}* ${name} 0..${p.max ?? "1"} ${p.fhir} ${q(p.short)} ${q(p.definition)}`];
  if (p.binding) out.push(`${indent}* ${name} from KG${pascal(p.binding)}VS (${strength(c, name)})`);
  for (const [child, cp] of Object.entries(p.children ?? {})) out.push(...elementLines(child, cp, c, `${indent}  `));
  return out;
}

function classModel(c: ClassSpec, layer: LayerSpec): string {
  const reuse = c.parent
    ? ` Derives from ${c.parent.name} (${c.parent.where}); ${Object.entries(c.properties).filter(([, p]) => p.inherited).map(([n]) => n).join(", ")} are its elements.`
    : c.correspondsTo
      ? ` Corresponds to ${c.correspondsTo.name}: ${c.correspondsTo.why}.`
      : "";
  const out = [
    `Logical: ${classModelName(c)}`,
    ...(c.parent ? [`Parent: ${c.parent.name}`] : []),
    `Title: ${q(`Knowledge graph ${layer.layer.toUpperCase()}: ${c.name}`)}`,
    `Description: ${q(`${c.note}${c.propertyNote ? ` ${c.propertyNote}` : ""}${reuse} Class IRI: ${c.iri}.`)}`,
    "",
    "* ^status = #active",
    '* ^publisher = "World Health Organization (WHO)"',
  ];
  for (const [name, p] of Object.entries(c.properties)) {
    if (p.inherited) continue;
    out.push(...elementLines(name, p, c));
  }
  return out.join("\n");
}

