/**
 * Turtle and Cypher views of each layer's TYPE graph (classes and licensed
 * edges), and the two files that merge every layer: ports of WHO smart-kg's
 * `tools/build-exports.mjs` `buildTurtle` and `buildCypher` (3f5e477).
 *
 * Committed rather than produced on demand, as smart-kg did, so someone can
 * open the model in the tool they use — Turtle in Protégé, Cypher in Neo4j —
 * without this toolchain. `emit.ts` writes them and `--check` keeps them
 * current. They carry no DAK data: a DAK's own graph is its IG build's.
 */
import { bindingOf, type ClassSpec, type LayerSpec } from "./ontology.ts";

const camel = (name: string): string =>
  name
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((w) => (/^[A-Z0-9]+$/.test(w) ? w : w[0]!.toUpperCase() + w.slice(1)))
    .join("");

const cy = (s: unknown): string => String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'");
const tt = (s: unknown): string => String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"');

/** A layer and what it imports: `scope` is the layer first, then everything it imports. */
export interface ExportScope {
  own: LayerSpec;
  scope: LayerSpec[];
}

const keyOf = (l: LayerSpec): string => l.layer.toLowerCase();
const classesIn = (scope: LayerSpec[]): Map<string, ClassSpec> => {
  const m = new Map<string, ClassSpec>();
  for (const l of [...scope].reverse()) for (const c of l.classes) m.set(c.id, c);
  return m;
};

/** Imported classes this layer builds on: an edge end or an `elaborates` target it does not declare. */
export function borrowedClassIds({ own }: ExportScope): string[] {
  const mine = new Set(own.classes.map((c) => c.id));
  const out = new Set<string>();
  for (const e of own.edges) for (const id of [e.source, e.target]) if (!mine.has(id)) out.add(id);
  for (const c of own.classes) if (c.elaborates && !mine.has(c.elaborates)) out.add(c.elaborates);
  return [...out].sort();
}

/** What each node kind means — the top of the class hierarchy, so every kind must have one. */
export const KIND_NOTES: Record<string, string> = {
  Source: "A published document, or a part of one, that guidance is stated in.",
  Concept: "A thing the guidance is about.",
  Reference: "A pointer out of this graph. Carries identity only; asserts nothing about the target.",
  Kit: "A Digital Adaptation Kit as a whole: metadata, and the nine components it contains.",
  Component: "One of the nine components DAK.fsh declares a kit must be able to hold. It points at the file that defines it and does not describe that file's interior.",
  Element: "A structured part of a component -- a requirement statement, a task entry. It exists as a node only where something outside its component needs to reach it.",
  Artefact: "A file, addressed as a whole. Shares its IRI with the L1 reference to the same file, so opening a file does not create a second name for it.",
  Structure: "An element inside a file. It has no identity apart from the file that contains it, and its vocabulary is the file format's, not WHO's.",
  Knowledge: "A FHIR knowledge artefact: something that encodes clinical or operational logic. Indexed by canonical URL; its interior stays in FHIR.",
  Conformance: "A FHIR conformance or definitional resource: something that constrains or defines structure and terminology. Indexed by canonical URL; its interior stays in FHIR.",
};

export function buildCypher(x: ExportScope): string {
  const { own } = x;
  const borrowed = borrowedClassIds(x);
  const L = [
    `// WHO SMART Guidelines knowledge graph -- ${own.layer.toUpperCase()} ONTOLOGY (type graph).`,
    "// Generated by smart-base/L1/schemas/emit.ts. Do not edit; edit the layer's Zod source.",
    "//",
    "// These are CLASSES and LICENSED EDGES, not DAK instance data. Loading this gives you the",
    "// schema to explore; a DAK's own graph is generated by that DAK's IG build.",
    "//",
    "// Every statement is MERGE, so re-running is safe.",
    "//",
    "// RUN THIS AGAINST A USER DATABASE, NOT `system`. The CREATE CONSTRAINT below is rejected",
    '// with "can only be executed in a user database" if `system` is selected, which is where',
    "// Neo4j Browser can land you after connecting. Switch first:",
    "//",
    "//     :use neo4j                                    (Browser, or your database's name)",
    "//     cypher-shell -d neo4j -f <this file>           (shell)",
    ...(borrowed.length
      ? [
          "//",
          `// REQUIRES ${(own.imports ?? []).map((l) => `${l}.cypher`).join(" and ")} TO BE LOADED FIRST.`,
          `// This layer licenses edges onto imported classes (${borrowed.join(", ")}). The MATCH`,
          "// statements below find nothing if those classes are absent, and Cypher does not treat",
          "// that as an error -- the edges would simply be missing. Verify with the query at the",
          "// end of this file.",
        ]
      : []),
    "",
    "CREATE CONSTRAINT kgclass_id IF NOT EXISTS",
    "FOR (c:KGClass) REQUIRE c.id IS UNIQUE;",
    "",
  ];
  for (const c of own.classes) {
    L.push(`MERGE (:KGClass:${c.kind} {id:'${cy(c.id)}', name:'${cy(c.name)}', kind:'${c.kind}', layer:'${cy(keyOf(own))}', iri:'${c.iri}'});`);
  }
  // `elaborates` is a class-level declaration, not a licensed edge: two classes describing one
  // artefact at different layers, sharing its IRI at instance level.
  const scopeClasses = classesIn(x.scope);
  for (const c of own.classes) {
    if (!c.elaborates || !scopeClasses.has(c.elaborates)) continue;
    L.push("");
    L.push(
      `MATCH (s:KGClass {id:'${cy(c.id)}'}), (t:KGClass {id:'${cy(c.elaborates)}'}) ` +
        `MERGE (s)-[:ELABORATES {predicate:'elaborates', ` +
        `note:'One artefact, one IRI: instances of these two classes are the same node, described at two layers.'}]->(t);`,
    );
  }
  L.push("");
  for (const e of own.edges) {
    const props = [`predicate:'${e.predicate}'`];
    if (e.qualifier) props.push(`qualifier:'${cy(e.qualifier)}'`);
    L.push(`MATCH (s:KGClass {id:'${e.source}'}), (t:KGClass {id:'${e.target}'}) MERGE (s)-[:${e.predicate.toUpperCase()} {${props.join(", ")}}]->(t);`);
  }
  if (borrowed.length) {
    L.push(
      "",
      `// Verification. Must return ${borrowed.length} rows -- one per imported class this layer`,
      "// builds on. Fewer means an imported layer was not loaded and edges above are missing.",
      `// MATCH (c:KGClass) WHERE c.id IN [${borrowed.map((id) => `'${id}'`).join(", ")}] RETURN c.id;`,
    );
  }
  return L.join("\n") + "\n";
}

export function buildTurtle(x: ExportScope): string {
  const { own } = x;
  const NS = own.namespace;
  // The ontology IRI and every owl:imports target are built from the layer's id, lower case.
  const ontologyIri = (name: string) => `${NS.replace(/\/$/, "")}/${name}`;
  const byId = classesIn(x.scope);
  const T = [
    `@prefix sgkg: <${NS}> .`,
    "@prefix owl:  <http://www.w3.org/2002/07/owl#> .",
    "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .",
    "@prefix skos: <http://www.w3.org/2004/02/skos/core#> .",
    "",
    `<${ontologyIri(keyOf(own))}> a owl:Ontology ;`,
    ...(own.imports ?? []).map((l) => `  owl:imports <${ontologyIri(l)}> ;`),
    `  rdfs:label "WHO SMART Guidelines ${own.layer.toUpperCase()} ontology" ;`,
    `  rdfs:comment "${tt(own.note)} Pairwise licensing is carried as sub-properties, ` +
      `because a relationship is licensed between specific class pairs while an OWL object ` +
      `property has one global domain and range." .`,
    "",
    "### Node kinds",
    "",
  ];
  const kinds = [...new Set(own.classes.map((c) => c.kind))].sort();
  const undescribed = kinds.filter((k) => !(k in KIND_NOTES));
  if (undescribed.length) throw new Error(`no description for node kind(s) ${undescribed.join(", ")} in exports.ts KIND_NOTES`);
  for (const kind of kinds) T.push(`sgkg:${kind} a owl:Class ; rdfs:label "${tt(kind)}" ; rdfs:comment "${tt(KIND_NOTES[kind])}" .`);
  T.push("", "### Classes", "");
  for (const c of own.classes) {
    T.push(`sgkg:${camel(c.name)} a owl:Class ;`);
    T.push(`  rdfs:subClassOf sgkg:${c.kind} ;`);
    T.push(`  rdfs:label "${tt(c.name)}" ;`);
    T.push(`  skos:notation "${c.id}" ;`);
    const el = c.elaborates ? byId.get(c.elaborates) : undefined;
    if (el) {
      T.push(`  rdfs:subClassOf sgkg:${camel(el.name)} ;`);
      T.push(
        `  skos:note "Instances share the IRI of the ${tt(el.name)} they elaborate: one artefact, one address, ` +
          `described opaquely at the layer above and structurally here." ;`,
      );
    }
    T.push(`  rdfs:comment "${tt(c.note)}" .`);
    T.push("");
  }
  if (own.valueSets.length) {
    T.push("### Value sets", "# Closed code lists bound to class properties. validate.ts rejects any other value.", "");
    const boundTo = new Map<string, string[]>();
    for (const c of byId.values()) {
      for (const [prop, binding] of Object.entries(c.valueSets ?? {})) {
        const { set } = bindingOf(binding);
        boundTo.set(set, [...(boundTo.get(set) ?? []), `${c.id}.${prop}`]);
      }
    }
    for (const v of own.valueSets) {
      const scheme = `${NS}valueset/${v.id}`;
      T.push(`<${scheme}> a skos:ConceptScheme ;`);
      T.push(`  skos:notation "${tt(v.id)}" ;`);
      if (v.source) T.push(`  skos:note "source: ${tt(v.source)}" ;`);
      if (boundTo.has(v.id)) T.push(`  skos:note "bound to: ${boundTo.get(v.id)!.join(", ")}" ;`);
      T.push(`  rdfs:comment "${tt(v.note)}" .`);
      for (const c of v.codes) {
        T.push(`<${scheme}#${c.code}> a skos:Concept ; skos:inScheme <${scheme}> ; skos:notation "${tt(c.code)}" ; skos:definition "${tt(c.definition)}" .`);
      }
      T.push("");
    }
  }
  T.push("### Object properties", "");
  const used = new Set(own.edges.map((e) => e.predicate));
  for (const p of own.predicates) {
    T.push(`sgkg:${p.predicate} a owl:ObjectProperty ;`);
    T.push(`  rdfs:label "${p.predicate}" ;`);
    T.push(`  rdfs:comment "${tt(p.note)}${used.has(p.predicate) ? "" : " -- declared but unused by the current model"}" .`);
    T.push("");
  }
  T.push(
    "### Licensed edges, as qualified sub-properties",
    "# One per (source class, predicate, target class) triple the layer licenses.",
    "# Domain and range on the sub-property is what preserves pairwise licensing: a single global",
    "# domain/range on the predicate would be a union of everything and would permit pairs the",
    "# model does not.",
    "",
  );
  const seen = new Map<string, number>();
  for (const e of own.edges) {
    const s = byId.get(e.source);
    const t = byId.get(e.target);
    if (!s || !t) throw new Error(`${own.layer}: edge ${e.source} ${e.predicate} ${e.target} names a class not in scope`);
    const base = `${e.predicate}_${camel(s.name)}_${camel(t.name)}`;
    const n = seen.get(base) ?? 0;
    seen.set(base, n + 1);
    const name = n === 0 ? base : `${base}_${n + 1}`;
    T.push(`sgkg:${name} a owl:ObjectProperty ;`);
    T.push(`  rdfs:subPropertyOf sgkg:${e.predicate} ;`);
    T.push(`  rdfs:domain sgkg:${camel(s.name)} ;`);
    T.push(`  rdfs:range sgkg:${camel(t.name)} ;`);
    if (e.qualifier) T.push(`  skos:note "qualifier: ${tt(e.qualifier)}" ;`);
    T.push(`  rdfs:label "${tt(s.name)} ${tt(e.qualifier ?? e.predicate)} ${tt(t.name)}" .`);
    T.push("");
  }
  return T.join("\n") + "\n";
}

/** Every layer's Cypher in one file, in dependency order, with the constraint stated once. */
export function allCypher(layers: { key: string; text: string }[]): string {
  return [
    "// WHO SMART Guidelines knowledge graph -- ALL LAYERS, in dependency order.",
    "// Generated by smart-base/L1/schemas/emit.ts. Do not edit; edit the layers' Zod source.",
    "//",
    "// RUN AGAINST A USER DATABASE, NOT `system`:",
    "//     :use neo4j                              (Neo4j Browser, or your database's name)",
    "//     cypher-shell -d neo4j -f all.cypher",
    "//",
    '// In Neo4j Browser, turn on "Enable multi statement query editor" in Settings before',
    "// pasting -- otherwise only the first statement runs.",
    "//",
    `// ${layers.map((l) => l.key).join(" -> ")}. Loading a layer before the ones it imports silently drops the`,
    "// edges that reach into them, because Cypher does not treat an empty MATCH as an error.",
    "",
    ...layers.map((l, i) => (i === 0 ? l.text : l.text.replace(/^CREATE CONSTRAINT[^\n]*\nFOR [^\n]*\n\n/m, ""))),
  ].join("\n");
}

/** Every layer's Turtle merged, prefixes once, for opening the whole model offline. */
export function allTurtle(layers: { key: string; text: string }[]): string {
  return [
    "# WHO SMART Guidelines knowledge graph -- ALL LAYERS merged.",
    "# Generated by smart-base/L1/schemas/emit.ts. Do not edit; edit the layers' Zod source.",
    "#",
    "# The per-layer files declare owl:imports, which a reasoner can only follow if the IRIs",
    "# resolve. This merge is for opening the whole model offline.",
    "",
    ...layers.map((l, i) => (i === 0 ? l.text : l.text.replace(/^@prefix[^\n]*\n/gm, ""))),
  ].join("\n");
}
