/**
 * The new form's `layers` read as `instances` (see "Two forms" above). Both
 * spelled is refused, and so is `layers` without `harnesses`. Anything that
 * is not an object passes through for the object schema to refuse.
 */
function readLayersSpelling(raw: unknown): unknown {
  if (raw === null || typeof raw !== "object" || Array.isArray(raw) || !("layers" in raw)) return raw;
  const { layers, ...rest } = raw as Record<string, unknown>;
  if ("instances" in rest) return { ...rest, __layersAndInstances: true };
  if (!("harnesses" in rest)) return { ...rest, instances: layers, __layersWithoutHarnesses: true };
  return { ...rest, instances: layers };
}

const IndexConfigObject = z
  .object({
    $schema: z.literal(INDEX_CONFIG_SCHEMA),
    _comment: z.string().optional(),
    /**
     * What this CHECKOUT is called. The index declares no instance of its own
     * (owner, 2026-10-08), so nothing else names it; `index:render` titles the
     * root `README.md` and `AGENTS.md` with it (owner, 2026-10-09: those two
     * are rendered files). Absent, they are titled generically.
     */
    title: z.string().min(1).optional(),
    /** One paragraph under that title, saying what the checkout is for. */
    description: z.string().min(1).optional(),
    instances: z
      .array(IndexInstanceSchema)
      .refine((xs) => new Set(xs.map((x) => x.name)).size === xs.length, { message: "instances: a name appears twice" })
      .refine((xs) => !xs.some((x) => x.name === HUB_LANDING), { message: `instances: \`${HUB_LANDING}\` is the landing keyword, not an instance name` }),
    /**
     * Which harnesses are INSTANTIATED here (cat-harness#1138), each an
     * instance of the Harness node kind. Absent is the old form: every layer
     * is read as instantiated, as before. Present, only these are, and the
     * file is written with `layers` rather than `instances`.
     */
    harnesses: z
      .array(IndexHarnessSchema)
      .refine((xs) => new Set(xs.map((x) => x.name)).size === xs.length, { message: "harnesses: a name appears twice" })
      .optional(),
    __layersAndInstances: z.literal(true).optional(),
    __layersWithoutHarnesses: z.literal(true).optional(),
    site: IndexSiteSchema.optional(),
    /**
     * The opt-in named sub-graphs switched on for THIS checkout, each
     * `<instance>.<directory id>` (cat-harness#991 step 23.4). An index root
     * declares no instance, so this is where it says what a layer's
     * declaration says in its own `enableSubgraphs`
     * (`schemas/kg/opt-in-subgraphs.ts`). Not inherited by any layer.
     */
    enableSubgraphs: z
      .array(z.string().regex(/^[a-z0-9][a-z0-9-]*\.[^\s]+$/, "`<instance>.<directory id>`, e.g. `cat-harness.sdlc`"))
      .refine((xs) => new Set(xs).size === xs.length, { message: "enableSubgraphs: an id is listed twice" })
      .optional(),
    /**
     * The steps of THIS checkout's own workflows that CI runs and the local
     * gate set does not, each with its reason ({@link GateExemptionsSchema}).
     * The index owns `.github/workflows/`, so it declares their exemptions,
     * in the same change as the step — never ahead of it in a layer.
     */
    gateExemptions: GateExemptionsSchema.optional(),
    /**
     * Sections that registered CONTENT TYPES declare about this repository,
     * keyed by the type's id: `"contentTypes": { "dak": { ... } }`.
     *
     * The platform knows only that each value is an object. What goes inside
     * is the business of the layer that registered the type, which reads and
     * validates its own section (owner, 2026-10-24: a DAK's metadata moves
     * into `index.config.json` and WHO adopts the file). A section's PRESENCE
     * is the marker, the same assertion a marker file makes: see
     * `IndexSectionMarker` in `content-type.ts`. It sits on the index for the
     * reason `site.agentRun` does: an IG repository may declare no instance
     * of its own, so its index is all it has.
     */
    contentTypes: z.record(IndexContentTypeIdSchema, z.record(z.string(), z.unknown())).optional(),
    /**
     * Who may consent to a remote mount in this checkout: `consent.by` on an
     * instance's `trust` must be one of them (`schemas/kg/mount-trust.ts`, roast
     * `1ygp` L4.2). The same field an instance declaration carries, here for
     * the checkout whose mounts the index lists and which may declare no
     * instance of its own (folio-assistant#2389). Declaring it in both is an
     * error, never a pick.
     */
    mountApprovers: z
      .array(z.string().min(1))
      .min(1)
      .refine((xs) => new Set(xs).size === xs.length, { message: "mountApprovers: a name appears twice" })
      .optional(),
  })
  .strict()
  .superRefine((c, ctx) => {
    if (c.__layersAndInstances) {
      ctx.addIssue({ code: "custom", path: ["layers"], message: "`layers` and `instances` are the same list in two forms: write one (`layers` with `harnesses`, cat-harness#1138)" });
    }
    if (c.__layersWithoutHarnesses) {
      ctx.addIssue({ code: "custom", path: ["layers"], message: "`layers` needs `harnesses` beside it, saying which are instantiated here; the old form spells the list `instances` (cat-harness#1138)" });
    }
    const layerNames = new Set(c.instances.map((i) => i.name));
    for (const [n, h] of (c.harnesses ?? []).entries()) {
      if (!layerNames.has(h.name)) {
        ctx.addIssue({ code: "custom", path: ["harnesses", n, "name"], message: `harnesses names \`${h.name}\`, which is not a layer this file lists` });
      }
      if (h.definedBy !== undefined && !layerNames.has(h.definedBy)) {
        ctx.addIssue({ code: "custom", path: ["harnesses", n, "definedBy"], message: `\`${h.definedBy}\` is not a layer this file lists` });
      }
    }
    const l = c.site?.landing;
    const landable = c.harnesses?.map((h) => h.name) ?? c.instances.map((i) => i.name);
    if (l !== undefined && l !== HUB_LANDING && !landable.includes(l)) {
      ctx.addIssue({
        code: "custom",
        path: ["site", "landing"],
        message: `site.landing names \`${l}\`, which is not ${c.harnesses ? "a harness" : "an instance"} this file lists (${landable.join(", ") || "none"})`,
      });
    }
  })
  .transform(({ __layersAndInstances: _a, __layersWithoutHarnesses: _b, ...c }) => c);

export const IndexConfigSchema = z.preprocess(readLayersSpelling, IndexConfigObject);
export type IndexConfig = z.output<typeof IndexConfigObject>;

/** The names instantiated per the index: `harnesses` when given, else every listed layer (the old form). */
export function indexHarnessNames(config: IndexConfig): string[] {
  return (config.harnesses?.map((h) => h.name) ?? config.instances.map((e) => e.name)).sort();
}

/** The inline `HarnessConfig` overrides an entry carries — every key but the index's own. */
export function inlineOverrides(entry: IndexInstance): Record<string, unknown> {
  const { name: _n, import: _i, source: _s, _comment: _c, ...rest } = entry as Record<string, unknown>;
  return rest;
}

/** The file an entry imports: its `import`, else `<name>.config.json`. Existence is the caller's question. */
export function importedConfigFilename(entry: IndexInstance): string {
  return entry.import ?? `${entry.name}${CONFIG_SUFFIX}`;
}

export type IndexConfigRead =
  | { state: "absent"; file: string }
  | { state: "ok"; file: string; config: IndexConfig }
  | { state: "unreadable"; file: string; why: string };

/**
 * Read `root/index.config.json`. ABSENT, UNREADABLE and OK are three answers:
 * an index that will not parse is never "no index", because the fallback it
 * would select is exactly what the file was written to override.
 */
export function readIndexConfig(root: string): IndexConfigRead {
  const file = join(root, INDEX_CONFIG_FILENAME);
  if (!existsSync(file)) return { state: "absent", file };
  let raw: unknown;
  try {
    raw = JSON.parse(readFileSync(file, "utf-8"));
  } catch (e) {
    return { state: "unreadable", file, why: `not JSON: ${(e as Error).message}` };
  }
  const p = IndexConfigSchema.safeParse(raw);
  if (!p.success) {
    const i = p.error.issues[0];
    return { state: "unreadable", file, why: `not a ${INDEX_CONFIG_SCHEMA} index: ${i ? `${i.path.join(".") || "(root)"}: ${i.message}` : "invalid"}` };
  }
  return { state: "ok", file, config: p.data };
}

/** {@link readIndexConfig}, throwing on UNREADABLE — for callers with no third state to report. */
export function requireIndexConfig(root: string): IndexConfig | undefined {
  const r = readIndexConfig(root);
  if (r.state === "unreadable") throw new Error(`${r.file} is ${r.why}`);
  return r.state === "ok" ? r.config : undefined;
}

// ── Declared mounts: ONE read path, ONE write path ──────────────────────────

/**
 * The fields of a declaration that mounting reads, and only those.
 *
 * Read STRUCTURALLY, the way the planner already reads an upstream's
 * declaration. A full {@link readDeclaration} needs every graph typology the
 * declaration names to be registered first. Some of those kinds are registered
 * by the very layers the mount fetches: a content instance may name a kind such
 * as `catalogue` that a layer it mounts registers. So in an empty checkout the full read refused the
 * mount that would have supplied the kind (bean `qump`). Whether the rest of the
 * declaration is valid is for the checks that read all of it once it is mounted.
 */
const MountFieldsSchema = z
  .object({
    name: z.string().min(1),
    remoteMounts: RemoteMountsSchema.optional(),
    mountApprovers: z.array(z.string().min(1)).min(1).optional(),
    directories: z.array(z.object({ path: z.string().min(1) }).passthrough()).default([]),
  })
  .passthrough();
export type MountFields = z.infer<typeof MountFieldsSchema>;

/** {@link MountFieldsSchema} for the instance at `instanceRoot`; `undefined` when it holds no declaration. Throws, with the file, on bad JSON or a bad field. */
export function readMountFields(instanceRoot: string): MountFields | undefined {
  const file = findDeclarationFile(instanceRoot);
  if (file === undefined) return undefined;
  const p = join(instanceRoot, file);
  let raw: unknown;
  try {
    raw = JSON.parse(readFileSync(p, "utf-8"));
  } catch (e) {
    throw new Error(`${p} is not valid JSON: ${e instanceof Error ? e.message : String(e)}`);
  }
  const r = MountFieldsSchema.safeParse(raw);
  if (!r.success) {
    const i = r.error.issues[0];
    throw new Error(`${p}: ${i ? `${i.path.join(".") || "(root)"}: ${i.message}` : "invalid"}`);
  }
  return r.data;
}

/** A remote instance entry as the `RemoteMount` the mount tooling consumes. */
export function remoteMountOf(entry: IndexInstance): RemoteMount | undefined {
  const src = entry.source;
  if (src === undefined || !("remote" in src)) return undefined;
  return { harness: entry.name, ...src.remote } as RemoteMount;
}

export interface DeclaredMounts {
  /** Where they were read from: the index, the declaration's `remoteMounts` (no index), or nowhere. */
  from: "index" | "declaration" | "none";
  /** The file read; absent for `none`. */
  file?: string;
  mounts: RemoteMount[];
}

/**
 * The remote mounts declared for the instance at `instanceRoot`.
 *
 * - `index.config.json` at `instanceRoot` present: its `source.remote`
 *   entries, and the declaration's `remoteMounts` MUST be empty — both
 *   carrying mounts THROWS, naming both files, because picking one would make
 *   the other a silent dead letter (a pin someone edited and nothing read).
 * - absent: the declaration's `remoteMounts`, exactly as before. A folio that
 *   has not migrated keeps working.
 *
 * Throws on an UNREADABLE index, never falls back past it.
 */
export function readDeclaredMounts(instanceRoot: string): DeclaredMounts {
  const idx = readIndexConfig(instanceRoot);
  if (idx.state === "unreadable") throw new Error(`${idx.file} is ${idx.why}`);
  const declFile = findDeclarationFile(instanceRoot);
  const declMounts = readMountFields(instanceRoot)?.remoteMounts ?? [];
  if (idx.state === "absent") {
    return declMounts.length > 0 ? { from: "declaration", file: join(instanceRoot, declFile!), mounts: declMounts } : { from: "none", mounts: [] };
  }
  const mounts = idx.config.instances.map(remoteMountOf).filter((m): m is RemoteMount => m !== undefined);
  if (declMounts.length > 0) {
    const both = declMounts.map((m) => m.harness).filter((h) => mounts.some((x) => x.harness === h));
    throw new Error(
      `remote mounts are declared in BOTH ${idx.file} and ${join(instanceRoot, declFile!)} \`remoteMounts\`` +
        (both.length ? ` (both declare ${both.join(", ")})` : ` (declaration: ${declMounts.map((m) => m.harness).join(", ")})`) +
        `. ${INDEX_CONFIG_FILENAME} is authoritative once it exists; move the declaration's entries with \`bun run cat index-config:migrate --write\`.`,
    );
  }
  return { from: "index", file: idx.file, mounts };
}

/**
 * Replace the remote mounts declared for the instance at `instanceRoot` —
 * THE write path. Every tool that writes mounts calls this; none writes
 * `remoteMounts` on a declaration any more.
 *
 * Writes `index.config.json`, seeding it with {@link buildIndexConfig} first
 * when the checkout has none (so the index it creates lists what the checkout
 * already instantiates, rather than instantiating only the mounts). Refuses
 * while the declaration still carries `remoteMounts`: that is the both-places
 * state {@link readDeclaredMounts} throws on, and writing would create it.
 *
 * A mount that is dropped loses its `source`; its entry stays when it still
 * says something (an import that exists, inline config), else it goes.
 */
export function writeDeclaredMounts(instanceRoot: string, mounts: readonly RemoteMount[]): { file: string; config: IndexConfig } {
  const parsed = RemoteMountsSchema.parse(mounts);
  const declMounts = readMountFields(instanceRoot)?.remoteMounts ?? [];
  if (declMounts.length > 0) {
    throw new Error(
      `${join(instanceRoot, findDeclarationFile(instanceRoot)!)} still declares \`remoteMounts\` (${declMounts.map((m) => m.harness).join(", ")}); ` +
        "run `bun run cat index-config:migrate --write` first so the mounts have one home",
    );
  }
  const idx = readIndexConfig(instanceRoot);
  if (idx.state === "unreadable") throw new Error(`${idx.file} is ${idx.why}`);
  const config: IndexConfig = idx.state === "ok" ? structuredClone(idx.config) : buildIndexConfig(instanceRoot).config;

  const wanted = new Map(parsed.map((m) => [m.harness, m]));
  const out: IndexInstance[] = [];
  for (const entry of config.instances) {
    const m = wanted.get(entry.name);
    if (m !== undefined) {
      const { harness: _h, ...remote } = m;
      out.push({ ...entry, source: { remote } });
      wanted.delete(entry.name);
      continue;
    }
    if (entry.source !== undefined && "remote" in entry.source) {
      const { source: _s, ...rest } = entry;
      const saysSomething =
        rest.import !== undefined || Object.keys(inlineOverrides(rest as IndexInstance)).length > 0 || existsSync(join(instanceRoot, importedConfigFilename(rest as IndexInstance)));
      if (saysSomething) out.push(rest as IndexInstance);
      continue;
    }
    out.push(entry);
  }
  for (const m of wanted.values()) {
    const { harness, ...remote } = m;
    out.push({ name: harness, source: { remote } });
  }
  const next = IndexConfigSchema.parse({ ...config, instances: out });
  const file = join(instanceRoot, INDEX_CONFIG_FILENAME);
  writeFileSync(file, formatIndexConfig(next));
  // The committed ignore block is part of the same write: a mount path the
  // index names and `.gitignore` does not is a mount `git add -A` commits.
  syncIgnoreBlock(instanceRoot, next);
  return { file, config: next };
}

/**
 * Add `entry` to `root/index.config.json` when the index exists and does not
 * list it yet — how `kg:instantiate` records a newly instantiated harness.
 * Returns whether the file changed. No index: nothing to add to (the root
 * config the caller wrote is then the instantiation, as before).
 */
export function addIndexInstance(root: string, entry: IndexInstance): boolean {
  const idx = readIndexConfig(root);
  if (idx.state === "unreadable") throw new Error(`${idx.file} is ${idx.why}`);
  if (idx.state === "absent" || idx.config.instances.some((e) => e.name === entry.name)) return false;
  const harnesses = idx.config.harnesses === undefined ? undefined : [...idx.config.harnesses, { name: entry.name }];
  const next = IndexConfigSchema.parse({ ...idx.config, instances: [...idx.config.instances, entry], ...(harnesses ? { harnesses } : {}) });
  writeFileSync(idx.file, formatIndexConfig(next));
  return true;
}

/** The canonical text of an index: two-space JSON, `$schema` first, a trailing newline. */
export function formatIndexConfig(config: IndexConfig): string {
  const { $schema, _comment, title, description, instances, harnesses, site, gateExemptions, contentTypes, mountApprovers, enableSubgraphs } = config;
  const layers = instances.map((e) => {
    const { name, _comment: c, import: imp, source, ...rest } = e as IndexInstance & Record<string, unknown>;
    return { name, ...(c !== undefined ? { _comment: c } : {}), ...(imp !== undefined ? { import: imp } : {}), ...(source !== undefined ? { source } : {}), ...rest };
  });
  const ordered = {
    $schema,
    ...(_comment !== undefined ? { _comment } : {}),
    ...(title !== undefined ? { title } : {}),
    ...(description !== undefined ? { description } : {}),
    // The new form writes `layers` + `harnesses`; the old one `instances` (cat-harness#1138).
    ...(harnesses !== undefined ? { layers, harnesses } : { instances: layers }),
    ...(site !== undefined ? { site } : {}),
    // Kept, like the exemptions below: a re-pin rewrites the index, and
    // dropping these would delete who may consent and what the content
    // types declare (folio-assistant#2389).
    ...(mountApprovers !== undefined ? { mountApprovers } : {}),
    // Kept too: dropping it here would switch the checkout's opt-in
    // sub-graphs off on the next re-pin (cat-harness#991 step 23.4, which
    // lost it to exactly that, folio-assistant#2926).
    ...(enableSubgraphs !== undefined ? { enableSubgraphs } : {}),
    ...(contentTypes !== undefined ? { contentTypes } : {}),
    // Last, and kept: dropping it here would make every rewrite of the index
    // silently delete the exemptions of its own workflows.
    ...(gateExemptions !== undefined ? { gateExemptions } : {}),
  };
  return `${JSON.stringify(ordered, null, 2)}\n`;
}

/**
 * The harnesses an old-form index really instantiates (cat-harness#1138, owner
 * card "A. Only what is instantiated", 2026-11-08): the landing, every entry
 * with a config of its own (inline fields, or a root `<name>.config.json` it
 * imports), and the sole layer of a one-layer index. A layer that is only
 * mounted for its content is not one. Returns `config` unchanged when it
 * already declares `harnesses`. Pure apart from checking which files exist.
 */
export function withDeclaredHarnesses(root: string, config: IndexConfig): IndexConfig {
  if (config.harnesses !== undefined) return config;
  const landing = config.site?.landing;
  const named = new Set<string>();
  if (config.instances.length === 1) named.add(config.instances[0]!.name);
  for (const e of config.instances) {
    if (e.name === landing) named.add(e.name);
    else if (Object.keys(inlineOverrides(e)).length > 0) named.add(e.name);
    else if (existsSync(join(root, importedConfigFilename(e)))) named.add(e.name);
  }
  // Layer order, so the list reads like the stack it is drawn from.
  const harnesses = config.instances.filter((e) => named.has(e.name)).map((e) => ({ name: e.name }));
  return IndexConfigSchema.parse({ ...config, harnesses }) as IndexConfig;
}

// ── Building an index from what a checkout holds today (the migration) ──────

export type MigrationFinding =
  | { kind: "unmatched-config"; file: string; detail: string }
  | { kind: "landing-undetermined"; detail: string }
  | { kind: "unreadable-config"; file: string; detail: string };

export interface IndexMigration {
  config: IndexConfig;
  findings: MigrationFinding[];
  /** The declaration file whose `remoteMounts` moved into the index, when any did. */
  movedFrom?: string;
  /** The remote mounts moved, by harness. */
  moved: string[];
}

/**
 * The index a checkout's CURRENT files imply — and, when an index already
 * exists, that index with whatever the declaration has gained since merged in.
 *
 * Reads only `root`: its declaration (when it has one), the instances
 * declared one level down, and its root `*.config.json`. Nothing of
 * folio-assistant's own root, so it runs on a standalone checkout of a
 * separated harness as well as on this monorepo.
 *
 * A root config is IMPORTED only when its stem names an instance this
 * checkout declares (the root, or one level down) or mounts. Anything else is
 * a FINDING and is not imported — a repository cut from a fork can inherit
 * the fork's own `<fork>.config.json`, and
 * importing it would instantiate a harness the repository does not hold.
 *
 * A remote mount already in the index with the SAME source is dropped from
 * the declaration (a re-run); with a DIFFERENT one it THROWS, naming both.
 */
export function buildIndexConfig(root: string, opts: { preferDeclaration?: boolean } = {}): IndexMigration {
  const findings: MigrationFinding[] = [];
  const idx = readIndexConfig(root);
  if (idx.state === "unreadable") throw new Error(`${idx.file} is ${idx.why}`);

  const declFile = findDeclarationFile(root);
  const decl = readDeclaration(root);
  const declMounts = decl?.remoteMounts ?? [];

  // Instances DECLARED in this checkout: the root's own, then one level down.
  const local = new Map<string, string>();
  for (const r of instanceRootsIn(root)) {
    try {
      const n = readDeclaration(r)?.name;
      if (n !== undefined && !local.has(n)) local.set(n, relative(root, r) || ".");
    } catch {
      // An unreadable declaration is `check:declaration-filename`'s finding;
      // here it means that directory cannot vouch for a config.
    }
  }

  const config: IndexConfig = idx.state === "ok" ? structuredClone(idx.config) : { $schema: INDEX_CONFIG_SCHEMA, instances: [] };
  const byName = new Map(config.instances.map((e) => [e.name, e]));

  // Remote mounts first: they decide which entries are remote.
  const moved: string[] = [];
  for (const m of declMounts) {
    const { harness, ...remote } = m;
    const have = byName.get(harness);
    const haveRemote = have?.source !== undefined && "remote" in have.source ? have.source.remote : undefined;
    if (haveRemote !== undefined) {
      if (JSON.stringify(sortKeys(haveRemote)) !== JSON.stringify(sortKeys(remote))) {
        // `--prefer-declaration`: a person has said the declaration is the
        // newer truth (a re-pin merged from main while this branch moved the
        // data). Explicit, never the default — the default refuses.
        if (opts.preferDeclaration) {
          have!.source = { remote };
          moved.push(harness);
          continue;
        }
        throw new Error(
          `\`${harness}\` is declared remote in BOTH ${idx.file} and ${join(root, declFile!)} \`remoteMounts\`, with different sources — ` +
            "reconcile by hand, or re-run with `--prefer-declaration` when the declaration is the newer pin; the migration will not pick one on its own",
        );
      }
    } else if (have !== undefined) {
      have.source = { remote };
    } else {
      const e: IndexInstance = { name: harness, source: { remote } };
      config.instances.push(e);
      byName.set(harness, e);
    }
    moved.push(harness);
  }

  // The root's own instance is instantiated here whether or not it has a config.
  if (decl?.name !== undefined && !byName.has(decl.name)) {
    const e: IndexInstance = { name: decl.name, source: { local: { at: "." } } };
    config.instances.push(e);
    byName.set(decl.name, e);
  }

  for (const stem of rootConfigStems(root)) {
    if (byName.has(stem)) continue;
    const at = local.get(stem);
    if (at === undefined) {
      findings.push({
        kind: "unmatched-config",
        file: join(root, `${stem}${CONFIG_SUFFIX}`),
        detail: `\`${stem}${CONFIG_SUFFIX}\` names no instance this checkout declares${decl ? ` (its own is \`${decl.name}\`)` : ""} or mounts — NOT imported. If it was inherited from a fork, remove it; if the harness is wanted, declare or mount it and re-run.`,
      });
      continue;
    }
    const e: IndexInstance = at === stem ? { name: stem } : { name: stem, source: { local: { at } } };
    config.instances.push(e);
    byName.set(stem, e);
  }

  // Landing: kept when the index already says; else the one flagged config.
  if (config.site?.landing === undefined && config.instances.length > 1) {
    const flagged: string[] = [];
    for (const e of config.instances) {
      const f = join(root, importedConfigFilename(e));
      if (!existsSync(f)) continue;
      try {
        const site = (JSON.parse(readFileSync(f, "utf-8")) as { site?: { landing?: unknown } } | null)?.site;
        if (site?.landing === true) flagged.push(e.name);
      } catch (err) {
        findings.push({ kind: "unreadable-config", file: f, detail: (err as Error).message });
      }
    }
    if (flagged.length === 1) config.site = { ...(config.site ?? {}), landing: flagged[0]! };
    else if (flagged.length >= 2) config.site = { ...(config.site ?? {}), landing: HUB_LANDING };
    else findings.push({ kind: "landing-undetermined", detail: `${config.instances.length} instances and no config flags \`site.landing\` — set \`site.landing\` in ${INDEX_CONFIG_FILENAME} by hand` });
  }

  // A NEW index reads root first, then the local instances, then the mounts —
  // the order a reader expects. An existing index keeps the order it has.
  if (idx.state === "absent") {
    const rank = (e: IndexInstance): number => (e.name === decl?.name ? 0 : e.source !== undefined && "remote" in e.source ? 2 : 1);
    config.instances = config.instances.map((e, i) => ({ e, i })).sort((a, b) => rank(a.e) - rank(b.e) || a.i - b.i).map((x) => x.e);
  }

  return {
    config: IndexConfigSchema.parse(config),
    findings,
    moved,
    ...(moved.length > 0 && declFile !== undefined ? { movedFrom: join(root, declFile) } : {}),
  };
}

function sortKeys(v: unknown): unknown {
  if (Array.isArray(v)) return v.map(sortKeys);
  if (v !== null && typeof v === "object") {
    return Object.fromEntries(Object.keys(v as object).sort().map((k) => [k, sortKeys((v as Record<string, unknown>)[k])]));
  }
  return v;
}

// ── The generated `.gitignore` block: one line per remote instance ──────────

export const IGNORE_BLOCK_BEGIN = "# BEGIN index mounts (generated from index.config.json — do not edit)";
export const IGNORE_BLOCK_END = "# END index mounts";

/**
 * Where a remote instance lands, relative to the index: the closure override
 * for the instance itself (`overrides.<name>.path`), else `<name>/` — the
 * same default `remote-mount.ts` gives an instance whose harness declares no
 * `mountDefaults.path`. No trailing slash.
 */
export function remoteMountPathOf(entry: IndexInstance): string | undefined {
  const m = remoteMountOf(entry);
  if (m === undefined) return undefined;
  const p = m.overrides?.[entry.name]?.path ?? `${entry.name}/`;
  return p.replace(/\/+$/, "");
}

/**
 * Every instance root the lock(s) in `root` say a mount laid down — the
 * CLOSURE, which reaches instances the index never names (a remote harness's
 * own `needs`). Read structurally, like `mountedUnder` in `git-corpus.ts`; an
 * unreadable or conflicting lock contributes nothing here (`mount:lock:check`
 * reports it).
 */
export function lockedMountPaths(root: string): string[] {
  const out = new Set<string>();
  for (const n of lockFilesIn(root).files) {
    try {
      const lock = JSON.parse(readFileSync(join(root, n), "utf-8")) as { instances?: { path?: unknown }[] };
      for (const i of lock.instances ?? []) if (typeof i.path === "string") out.add(i.path.replace(/\/+$/, ""));
    } catch {
      // see above
    }
  }
  return [...out].sort();
}

/**
 * The block's lines, markers included: one `/<path>/` per remote instance in
 * index order, then every further path in `extra` (the locked closure,
 * {@link lockedMountPaths}) sorted — so an instance a mount brought in
 * transitively is ignored as surely as one the index names.
 */
export function ignoreBlockLines(config: IndexConfig, extra: readonly string[] = []): string[] {
  const paths = config.instances.map(remoteMountPathOf).filter((p): p is string => p !== undefined);
  const more = [...new Set(extra.map((p) => p.replace(/\/+$/, "")))].filter((p) => !paths.includes(p)).sort();
  return [IGNORE_BLOCK_BEGIN, ...[...paths, ...more].map((p) => `/${p}/`), IGNORE_BLOCK_END];
}

export type IgnoreBlockState =
  | { state: "current" }
  | { state: "missing"; detail: string }
  | { state: "drift"; detail: string; want: string[]; have: string[] };

function blockRange(lines: string[]): { begin: number; end: number } | undefined | "malformed" {
  const begin = lines.indexOf(IGNORE_BLOCK_BEGIN);
  const end = lines.indexOf(IGNORE_BLOCK_END);
  if (begin < 0 && end < 0) return undefined;
  if (begin < 0 || end < begin || lines.lastIndexOf(IGNORE_BLOCK_BEGIN) !== begin || lines.lastIndexOf(IGNORE_BLOCK_END) !== end) return "malformed";
  return { begin, end };
}

/** Does `root/.gitignore` carry the block `config` (and the lock beside it) implies? Reads only. */
export function checkIgnoreBlock(root: string, config: IndexConfig, extra: readonly string[] = lockedMountPaths(root)): IgnoreBlockState {
  const file = join(root, ".gitignore");
  const want = ignoreBlockLines(config, extra);
  if (!existsSync(file)) return { state: "missing", detail: `${file} does not exist — run \`bun run cat index-config:migrate --write\`` };
  const lines = readFileSync(file, "utf-8").split("\n");
  const r = blockRange(lines);
  if (r === undefined) return { state: "missing", detail: `${file} has no \`${IGNORE_BLOCK_BEGIN}\` block — run \`bun run cat index-config:migrate --write\`` };
  if (r === "malformed") return { state: "drift", detail: `${file}: the index-mounts markers are unpaired or repeated`, want, have: [] };
  const have = lines.slice(r.begin, r.end + 1);
  if (JSON.stringify(have) === JSON.stringify(want)) return { state: "current" };
  return { state: "drift", detail: `${file}'s index-mounts block disagrees with ${INDEX_CONFIG_FILENAME}`, want, have };
}

/** The `.gitignore` text with the block in place: replaced between its markers, else appended. A malformed pair throws. */
export function withIgnoreBlock(text: string, config: IndexConfig, file = ".gitignore", extra: readonly string[] = []): string {
  const lines = text.split("\n");
  const want = ignoreBlockLines(config, extra);
  const r = blockRange(lines);
  if (r === "malformed") throw new Error(`${file}: the index-mounts markers are unpaired or repeated — fix by hand`);
  if (r !== undefined) return [...lines.slice(0, r.begin), ...want, ...lines.slice(r.end + 1)].join("\n");
  const base = text === "" || text.endsWith("\n") ? text : `${text}\n`;
  return `${base}${base === "" ? "" : "\n"}${want.join("\n")}\n`;
}

/** Write the block into `root/.gitignore` ({@link withIgnoreBlock}). Returns whether the file changed. */
export function syncIgnoreBlock(root: string, config: IndexConfig, extra: readonly string[] = lockedMountPaths(root)): boolean {
  const file = join(root, ".gitignore");
  const text = existsSync(file) ? readFileSync(file, "utf-8") : "";
  const next = withIgnoreBlock(text, config, file, extra);
  if (next === text) return false;
  writeFileSync(file, next);
  return true;
}
