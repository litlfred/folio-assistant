/**
 * A viewer route that ignores itself (a `.gitignore` of `*`) is outside the
 * mount digest, like a declared `builtAtPublish` path (bean
 * folio-assistant-uldr, design A): a publish build that writes
 * a higher layer's viewer routes onto the host's site must not make the host's
 * mount read as modified.
 */
import { describe, expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { coveredFiles, digestOf, isSelfIgnore, withoutSelfIgnored } from "../scripts/mount-from-lock.ts";

const put = (root: string, rel: string, text: string): void => {
  mkdirSync(join(root, rel, ".."), { recursive: true });
  writeFileSync(join(root, rel), text);
};

describe("self-ignoring routes", () => {
  test("only a lone `*` pattern is a self-ignore", () => {
    expect(isSelfIgnore("# Generated by x\n*\n")).toBe(true);
    expect(isSelfIgnore("*")).toBe(true);
    expect(isSelfIgnore("*\n!keep.md\n")).toBe(false);
    expect(isSelfIgnore("*.svg\n")).toBe(false);
    expect(isSelfIgnore("# nothing\n")).toBe(false);
  });

  test("a built route leaves the digest unchanged", () => {
    const dir = mkdtempSync(join(tmpdir(), "self-ignore-"));
    try {
      put(dir, "x.json", "{}");
      put(dir, "docs/index.md", "pinned");
      const before = digestOf(dir);
      put(dir, "docs/en/upper/glossary/.gitignore", "# Generated\n*\n");
      put(dir, "docs/en/upper/glossary/index.md", "built at publish");
      put(dir, "docs/fr/upper/glossary/.gitignore", "*\n");
      put(dir, "docs/fr/upper/glossary/a/index.md", "built at publish");
      expect(digestOf(dir)).toEqual(before);
      expect(coveredFiles(dir)).toEqual(["docs/index.md", "x.json"]);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  test("a partial ignore, and the instance's own root .gitignore, hide nothing", () => {
    const dir = mkdtempSync(join(tmpdir(), "self-ignore-"));
    try {
      put(dir, ".gitignore", "*\n");
      put(dir, "docs/a/.gitignore", "*.svg\n");
      put(dir, "docs/a/b.md", "pinned");
      expect(withoutSelfIgnored(dir, [".gitignore", "docs/a/.gitignore", "docs/a/b.md"])).toEqual([".gitignore", "docs/a/.gitignore", "docs/a/b.md"]);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});
