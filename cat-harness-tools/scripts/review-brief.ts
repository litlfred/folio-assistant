/**
 * The review page's "What to expect in this review" pane: what the reviewer
 * should find on the page, read from the pull request and the issue it
 * closes.
 *
 * ## Any branch, not only change sets
 *
 * The pane reads the one thing every preview has: its pull request. A change
 * set adds detail when it is there.
 *
 * - The PR body may hold a section between `<!-- review-brief -->` and
 *   `<!-- /review-brief -->`. Then the pane shows only that section. Change-set
 *   agents write the Overall line and one disposition per comment number there.
 * - Otherwise the pane shows the PR body, without HTML comments, the
 *   attribution line and the generated footer.
 * - A title starting `CS-nnn` names the change set.
 * - The issue is the first `Closes/Fixes/Resolves #n` in the body, or the
 *   banner's `issue`.
 * - "Sections this change touches" lists the sections the ChangeSet changed, most changes
 *   first. It needs no PR at all.
 *
 * ## Live first, then the snapshot
 *
 * The page asks the GitHub API for the PR and issue when it opens, so a body
 * edited after the build still shows. When that fails (rate limit, offline, a
 * private repository) it reads `review-brief.json`, written when the preview
 * was staged, and says which one it shows.
 *
 * ## Safe by construction
 *
 * PR text is untrusted. It is drawn with DOM APIs and `textContent` only, and
 * a link is kept only when it is `https:` or `http:`.
 *
 * Every function here is self-contained: `gen-review-page` embeds them with
 * `toString()`, so the functions the tests drive are the ones that run.
 */

export interface BriefPr { number: number; title: string; body: string | null; url: string }
export interface BriefIssue { number: number; title: string; url: string }

export interface BriefModel {
  /** "live" from the API, "snapshot" from review-brief.json, or "none". */
  source: "live" | "snapshot" | "none";
  pr: BriefPr | null;
  issue: BriefIssue | null;
  /** `CS-001` when the PR title names a change set, else null. */
  changeSet: string | null;
  /** The Markdown the pane shows. */
  text: string;
  /** True when `text` is the PR's own `review-brief` section. */
  marked: boolean;
  /** When the snapshot was taken, for "snapshot". */
  fetchedAt: string | null;
}

/** `{ owner, repo }` from the banner's `branchUrl`, or null. */
export function briefRepo(st: { branchUrl?: string; prUrl?: string } | null): { owner: string; repo: string } | null {
  const m = String((st && (st.branchUrl || st.prUrl)) || "").match(/^https:\/\/github\.com\/([A-Za-z0-9_.-]+)\/([A-Za-z0-9_.-]+)\//);
  return m ? { owner: m[1]!, repo: m[2]! } : null;
}

/** The issue number a PR body closes, or null. */
export function closedIssue(body: string | null): number | null {
  const m = String(body || "").match(/\b(?:close[sd]?|fix(?:e[sd])?|resolve[sd]?)\s+#(\d+)\b/i);
  return m ? Number(m[1]) : null;
}

/** The part of a PR body the pane shows, and whether it was the marked section. */
export function briefText(body: string | null): { text: string; marked: boolean } {
  const b = String(body || "").replace(/\r\n?/g, "\n");
  const m = b.match(/<!--\s*review-brief\s*-->([\s\S]*?)<!--\s*\/review-brief\s*-->/i);
  if (m) return { text: m[1]!.trim(), marked: true };
  let t = b.replace(/<!--[\s\S]*?-->/g, "");
  // The generated footer: a rule followed only by "_Generated by …_" or the robot line.
  t = t.replace(/\n-{3,}\s*\n(?:\s*(?:_Generated by[^\n]*|🤖[^\n]*|https:\/\/claude\.ai\/code\/\S*)\s*\n?)+\s*$/, "\n");
  t = t.split("\n").filter(function (l) { return !/^_Requested by \*\*/.test(l.trim()); }).join("\n");
  return { text: t.trim(), marked: false };
}

/** The pane's model from what was fetched. Either side may be missing. */
export function briefModel(o: {
  staging: { pr?: string; issue?: string | null; issueUrl?: string | null } | null;
  pr: BriefPr | null;
  issue: BriefIssue | null;
  source: "live" | "snapshot" | "none";
  fetchedAt?: string | null;
}): BriefModel {
  const t = briefText(o.pr ? o.pr.body : null);
  const cs = o.pr ? String(o.pr.title).match(/^\s*(CS-\d+)\b/i) : null;
  return {
    source: o.pr ? o.source : "none",
    pr: o.pr,
    issue: o.issue,
    changeSet: cs ? cs[1]!.toUpperCase() : null,
    text: t.text,
    marked: t.marked,
    fetchedAt: o.fetchedAt || null,
  };
}

/** Sections with changes, most first: `{ section, count }`, at most `max`. */
export function whereToLook(changes: Array<{ head?: { section?: string }; base?: { section?: string } }>, max: number): Array<{ section: string; count: number }> {
  const by: Record<string, number> = {};
  const order: string[] = [];
  (changes || []).forEach(function (c) {
    const s = (c.head || c.base || {}).section || "(listed in no section)";
    if (!(s in by)) { by[s] = 0; order.push(s); }
    by[s]!++;
  });
  return order
    .map(function (s, i) { return { section: s, count: by[s]!, i: i }; })
    .sort(function (a, b) { return b.count - a.count || a.i - b.i; })
    .slice(0, max)
    .map(function (r) { return { section: r.section, count: r.count }; });
}

/**
 * A small Markdown subset as blocks: headings, bullet and numbered lists,
 * rules, and paragraphs. Enough for a PR body; anything else is a paragraph.
 */
export function briefBlocks(md: string): Array<{ type: "h" | "p" | "ul" | "ol" | "hr"; level?: number; text?: string; items?: string[] }> {
  const out: Array<{ type: "h" | "p" | "ul" | "ol" | "hr"; level?: number; text?: string; items?: string[] }> = [];
  let para: string[] = [];
  let list: { type: "ul" | "ol"; items: string[] } | null = null;
  function flush() {
    if (para.length) { out.push({ type: "p", text: para.join(" ") }); para = []; }
    if (list) { out.push(list); list = null; }
  }
  String(md || "").split("\n").forEach(function (raw) {
    const l = raw.replace(/\s+$/, "");
    let m;
    if (!l.trim()) { flush(); return; }
    if ((m = l.match(/^\s{0,3}(#{1,6})\s+(.*)$/))) { flush(); out.push({ type: "h", level: m[1].length, text: m[2] }); return; }
    if (/^\s{0,3}(?:-{3,}|\*{3,}|_{3,})\s*$/.test(l)) { flush(); out.push({ type: "hr" }); return; }
    if ((m = l.match(/^\s{0,3}([-*+]|\d+[.)])\s+(.*)$/))) {
      const type = /\d/.test(m[1]) ? "ol" : "ul";
      if (para.length) { out.push({ type: "p", text: para.join(" ") }); para = []; }
      if (!list || list.type !== type) { if (list) out.push(list); list = { type: type, items: [] }; }
      list.items.push(m[2]);
      return;
    }
    // A continuation line of a list item, or of a paragraph.
    if (list && /^\s+\S/.test(raw)) { list.items[list.items.length - 1] += " " + l.trim(); return; }
    if (list) { out.push(list); list = null; }
    para.push(l.trim());
  });
  flush();
  return out;
}

/**
 * Appends `text` to `parent` with `**bold**`, `` `code` `` and `[label](url)`
 * drawn, and bare https URLs linked. Only http(s) links are kept; any other
 * scheme stays as plain text.
 */
export function briefInline(doc: Document, parent: Element, text: string): void {
  const re = /\*\*([^*]+)\*\*|`([^`]+)`|\[([^\]]+)\]\(([^)\s]+)\)|(https?:\/\/[^\s<>()]+[^\s<>().,;:!?'"])/g;
  const s = String(text || "");
  let last = 0;
  let m;
  while ((m = re.exec(s))) {
    if (m.index > last) parent.appendChild(doc.createTextNode(s.slice(last, m.index)));
    // Bold may hold a link ("**No. [136](…#PC-0137):**"), so its inside is drawn the same way.
    if (m[1] !== undefined) { const b = doc.createElement("strong"); briefInline(doc, b, m[1]); parent.appendChild(b); }
    else if (m[2] !== undefined) { const c = doc.createElement("code"); c.textContent = m[2]; parent.appendChild(c); }
    else {
      const label = m[3] !== undefined ? m[3] : m[5]!;
      const url = m[3] !== undefined ? m[4]! : m[5]!;
      if (/^https?:\/\//i.test(url)) {
        const a = doc.createElement("a");
        a.setAttribute("href", url);
        a.setAttribute("rel", "noopener");
        a.textContent = label;
        parent.appendChild(a);
      } else parent.appendChild(doc.createTextNode(m[0]));
    }
    last = re.lastIndex;
  }
  if (last < s.length) parent.appendChild(doc.createTextNode(s.slice(last)));
}

/**
 * Draws the pane into `box`. `where` is the ChangeSet's sections (or null
 * before it loads, or when there is none); `jump` moves focus to a section.
 * Uses `briefBlocks` and `briefInline`, which the page defines beside it.
 */
export function renderBrief(doc: Document, box: Element, model: BriefModel, where: Array<{ section: string; count: number }> | null, jump: ((s: string) => void) | null): void {
  while (box.firstChild) box.removeChild(box.firstChild);
  function el(tag: string, text?: string, cls?: string) {
    const e = doc.createElement(tag);
    if (text !== undefined) e.textContent = text;
    if (cls) e.className = cls;
    return e;
  }
  const h = el("h2", "What to expect in this review");
  h.id = "brief-h";
  box.appendChild(h);
  const head = el("p");
  if (model.changeSet) { head.appendChild(el("span", "Change set " + model.changeSet, "brief-chip")); head.appendChild(doc.createTextNode(" ")); }
  if (model.pr) {
    const a = el("a", "PR #" + model.pr.number + ": " + model.pr.title);
    if (/^https:\/\//.test(model.pr.url)) a.setAttribute("href", model.pr.url);
    head.appendChild(a);
  } else head.appendChild(el("span", "No pull request found for this preview, so there is no summary from it.", "muted"));
  if (model.issue) {
    head.appendChild(doc.createTextNode(" · "));
    const ia = el("a", "Issue #" + model.issue.number + (model.issue.title ? ": " + model.issue.title : ""));
    if (/^https:\/\//.test(model.issue.url)) ia.setAttribute("href", model.issue.url);
    head.appendChild(ia);
  }
  box.appendChild(head);
  if (model.pr) {
    const body = el("div", undefined, "brief-body");
    const blocks = briefBlocks(model.text);
    if (!blocks.length) body.appendChild(el("p", "The pull request has no description.", "muted"));
    blocks.forEach(function (b) {
      if (b.type === "hr") { body.appendChild(el("hr")); return; }
      if (b.type === "h") { const hh = el("h3"); briefInline(doc, hh, b.text || ""); body.appendChild(hh); return; }
      if (b.type === "p") { const p = el("p"); briefInline(doc, p, b.text || ""); body.appendChild(p); return; }
      const l = el(b.type);
      (b.items || []).forEach(function (it) { const li = el("li"); briefInline(doc, li, it); l.appendChild(li); });
      body.appendChild(l);
    });
    box.appendChild(body);
  }
  if (where && where.length) {
    box.appendChild(el("h3", "Sections this change touches"));
    const ul = el("ul", undefined, "brief-where");
    where.forEach(function (w) {
      const li = el("li");
      const name = w.section.indexOf("::") >= 0 ? w.section.split("::").pop() || w.section : w.section;
      if (jump) {
        const btn = el("button", name, "linklike");
        btn.setAttribute("type", "button");
        btn.addEventListener("click", function () { jump(w.section); });
        li.appendChild(btn);
      } else li.appendChild(el("span", name));
      li.appendChild(doc.createTextNode(" (" + w.count + " changed block" + (w.count === 1 ? "" : "s") + ")"));
      ul.appendChild(li);
    });
    box.appendChild(ul);
  }
  const src = model.source === "live" ? "Read from GitHub when this page opened."
    : model.source === "snapshot" ? "Read from the copy taken when this preview was staged" + (model.fetchedAt ? " (" + model.fetchedAt + ")" : "") + ": GitHub could not be reached, so a later edit to the pull request may not show."
    : "";
  if (src) box.appendChild(el("p", src + (model.marked ? " This is the pull request's review brief." : ""), "muted"));
}
