#!/usr/bin/env bun
/**
 * Regenerate `scripts/lib/gherkin-dialects.ts` — the structural keywords of
 * every Gherkin dialect — from Cucumber's `gherkin-languages.json`.
 *
 * Owner, 2026-11-07: Gherkin dialects are allowed, so a translated `.feature`
 * file stays valid. The scanner needs only the keywords that START an element
 * (Feature, Rule, Background, Scenario, Scenario Outline, Examples); steps are
 * not read. So this keeps those six per language and drops the rest, rather
 * than taking a parser dependency for one table.
 *
 * The source is `@cucumber/gherkin` (MIT), file `src/gherkin-languages.json`.
 * Pass its path and the package version it came from:
 *
 *   bun run cat-harness-tools/scripts/gen-gherkin-dialects.ts <gherkin-languages.json> <version>
 *
 * @module scripts/gen-gherkin-dialects
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const KEYS = ["feature", "rule", "background", "scenario", "scenarioOutline", "examples"] as const;

if (import.meta.main) {
  const [src, version] = process.argv.slice(2);
  if (!src || !version) {
    console.error("usage: gen-gherkin-dialects.ts <gherkin-languages.json> <@cucumber/gherkin version>");
    process.exit(2);
  }
  const all = JSON.parse(readFileSync(src, "utf-8")) as Record<string, Record<string, string[] | string>>;
  const table: Record<string, Record<string, string[]>> = {};
  for (const lang of Object.keys(all).sort()) {
    table[lang] = Object.fromEntries(
      KEYS.map((k) => [k, [...new Set((all[lang][k] as string[]).map((w) => w.trim()).filter((w) => w && w !== "*"))]]),
    );
  }
  const out = [
    "// GENERATED by scripts/gen-gherkin-dialects.ts — do not edit by hand.",
    `// Source: @cucumber/gherkin ${version}, src/gherkin-languages.json (MIT, Copyright (c) Cucumber Ltd).`,
    "// Only the keywords that start an element are kept; step keywords are not read by the scanner.",
    "",
    "/** A dialect's structural keywords, each without its trailing colon. */",
    "export interface GherkinDialect {",
    ...KEYS.map((k) => `  ${k}: readonly string[];`),
    "}",
    "",
    "/** Every dialect, keyed by its `# language:` code. */",
    `export const GHERKIN_DIALECTS: Readonly<Record<string, GherkinDialect>> = ${JSON.stringify(table, null, 2)};`,
    "",
  ].join("\n");
  writeFileSync(join(import.meta.dir, "lib", "gherkin-dialects.ts"), out);
  console.log(`wrote ${Object.keys(table).length} dialects`);
}
