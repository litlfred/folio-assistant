#!/usr/bin/env bash
# gen-bat-wrappers.sh — write a Windows .bat entry point beside every .sh a
# user runs by hand or wires into a config (hooks, .mcp.json, docs).
#
# Each .bat locates Git Bash (Git\bin\bash.exe — never the WSL launcher in
# System32) and runs the sibling .sh with the same arguments. They are
# wrappers, not ports: the scripts stay bash, and Git for Windows is already
# a prerequisite of `git` on that platform.
#
# Usage:
#   cat-harness-tools/scripts/gen-bat-wrappers.sh          # (re)write every wrapper
#   cat-harness-tools/scripts/gen-bat-wrappers.sh --check  # exit 1 if any wrapper is missing or stale
#
# To add a script: append it to WRAPPED below and re-run. Deliberately NOT
# wrapped — a .bat would only relocate the failure:
#   deploy/*.sh, install-tex.sh, setup-singular.sh,
#   setup-elan-symlinks.sh, adapters/mcp-server/install.sh   (Linux host: apt/sudo/symlinks)
#   scripts/lib/*.sh                                         (sourced, not run)
#   scripts/git-hooks/auto-commit-feedback.sh                (git runs it via sh)
#   scripts/git-hooks/claude-pre-push.sh                     (Claude Code runs it via sh)
#   .github/scripts/generate-diff.sh, latexmk-compile.sh     (CI only)
#   docker-latex-build/build-pdf.sh, smoke-test-libraries.sh (qou-specific leftovers)
set -euo pipefail

INSTANCE_ROOT="$(bash "$(dirname "$0")/lib/harness-root.sh")"
REPO_ROOT="$(cd "$INSTANCE_ROOT/.." && pwd)"
cur="$REPO_ROOT"
while [ "$cur" != "/" ] && [ "$cur" != "." ]; do
  if [ -f "$cur/index.config.json" ]; then
    REPO_ROOT="$cur"
    break
  fi
  cur="$(dirname "$cur")"
done
cd "$REPO_ROOT"

WRAPPED=(
  .claude/skills/hooks/session-start.sh
  cat-harness-tools/scripts/audit-library-coherence.sh
  cat-harness-tools/scripts/check-branch-todos.sh
  cat-harness-tools/scripts/rename-special-branch.sh
  cat-harness-tools/scripts/check-no-lean-artifacts.sh
  cat-harness-tools/scripts/check-todos.sh
  cat-harness-tools/scripts/check-upstream.sh
  cat-harness-tools/scripts/delivery-summary.sh
  folio-assistant-sci/adapters/paper/latex/feature-build.sh
  cat-harness-tools/scripts/folio-port.sh
  cat-harness-tools/scripts/git-hooks/install.sh
  cat-harness-tools/scripts/google-drive-mcp.sh
  cat-harness-tools/scripts/greeting-task-selection.sh
  cat-harness-tools/scripts/install-beans.sh
  cat-harness-tools/scripts/install-bun.sh
  cat-harness-tools/scripts/install-lean-atlas.sh
  cat-harness-tools/scripts/lean-build-all.sh
  cat-harness-tools/scripts/lean-build-timed.sh
  cat-harness-tools/scripts/lean-cache-dump.sh
  cat-harness-tools/scripts/lean-closure-orchestrator.sh
  cat-harness-tools/scripts/open-folio-assistant.sh
  cat-harness-tools/scripts/render-on-change.sh
  cat-harness-tools/scripts/render-pre-commit.sh
  cat-harness-tools/scripts/sage-mcp.sh
  cat-harness-tools/scripts/session-start-coord-sweep.sh
  cat-harness-tools/scripts/sign.sh
  cat-harness-tools/scripts/start-folio-assistant.sh
  cat-harness-tools/scripts/start-viewer.sh
  cat-harness-tools/scripts/tests/run-tests.sh
  cat-harness-tools/scripts/upload-to-uploads.sh
  cat-harness-tools/scripts/watch-main-prompt.sh
)

render() {
  local sh="$1"
  # CRLF on purpose: cmd.exe parses LF-only batch files, but mis-handles some
  # labels and multi-line blocks; CRLF is the safe encoding for .bat.
  printf '%s\r\n' \
    '@echo off' \
    'setlocal' \
    "rem Windows entry point for $sh -- generated by cat-harness-tools/scripts/gen-bat-wrappers.sh; do not hand-edit." \
    'rem Runs the sibling .sh under Git Bash with the same arguments. Git for Windows is required.' \
    'set "SCRIPT=%~dpn0.sh"' \
    'set "BASH="' \
    'for %%B in ("%ProgramFiles%\Git\bin\bash.exe" "%ProgramFiles(x86)%\Git\bin\bash.exe" "%LocalAppData%\Programs\Git\bin\bash.exe") do if not defined BASH if exist %%B set "BASH=%%~B"' \
    "if not defined BASH for /f \"delims=\" %%G in ('where git.exe 2^>nul') do if not defined BASH if exist \"%%~dpG..\bin\bash.exe\" set \"BASH=%%~dpG..\bin\bash.exe\"" \
    'if not defined BASH (' \
    '  echo [%~nx0] Git Bash not found. Install Git for Windows from https://git-scm.com/download/win 1>&2' \
    '  exit /b 2' \
    ')' \
    'if not exist "%SCRIPT%" (' \
    '  echo [%~nx0] missing sibling script: %SCRIPT% 1>&2' \
    '  exit /b 2' \
    ')' \
    '"%BASH%" "%SCRIPT%" %*' \
    'exit /b %ERRORLEVEL%'
}

# Why an ABSENT entry is not this root's to wrap, or nothing when it is
# (cat-harness-tools#1701, smart-ips-pilgrimage#13). WRAPPED lists the scripts
# of the HARNESS index — the root carrying the gates workflow — and of the
# layers it mounts. In a CONTENT root (no such workflow, the same generic rule
# as scripts/lib/root-gate-set.ts `rootProfile`) an entry is excused when no
# mounted instance holds it: a root-level path such as .claude/skills/... is
# the harness root's, and a layer this root does not mount (no <seg>/<seg>.json)
# is not here at all. An absent entry under a MOUNTED instance is still an
# error, and a harness root is judged exactly as before.
not_ours() {
  local sh="$1" seg="${1%%/*}"
  [ -f "$REPO_ROOT/.github/workflows/code-quality-gates.yml" ] && return 1
  [ "$seg" != "$sh" ] && [ -f "$REPO_ROOT/$seg/$seg.json" ] && return 1
  echo "a content root (no .github/workflows/code-quality-gates.yml), and no mounted instance holds it: it is the harness index's or an unmounted layer's"
}

check="${1:-}"
stale=0
excused=0
for sh in "${WRAPPED[@]}"; do
  target_sh="$sh"
  if [ ! -f "$target_sh" ] && [ -f "$INSTANCE_ROOT/${sh#cat-harness/}" ]; then
    target_sh="$INSTANCE_ROOT/${sh#cat-harness/}"
  fi
  if [ ! -f "$target_sh" ] && why="$(not_ours "$sh")"; then
    echo "· $sh not applicable here — $why"
    excused=$((excused + 1))
    continue
  fi
  [ -f "$target_sh" ] || { echo "ERROR: $sh does not exist — remove it from WRAPPED" >&2; exit 2; }
  bat="${target_sh%.sh}.bat"
  if [ "$check" = "--check" ]; then
    if [ ! -f "$bat" ] || ! cmp -s <(render "$sh") "$bat"; then
      echo "STALE: $bat"; stale=1
    fi
  else
    render "$sh" > "$bat"
    echo "wrote $bat"
  fi
done
if [ "$check" = "--check" ]; then
  [ "$stale" = 0 ] && { note=""; [ "$excused" -gt 0 ] && note=" ($excused not applicable here)"; echo "all $((${#WRAPPED[@]} - excused)) .bat wrappers up to date$note"; }
  exit $stale
fi
