const NOT_THIS_PASS: readonly string[] = [VIEWER_DIR];

/**
 * Where a rail's platform links point when the site is NOT the platform's.
 *
 * A folio's own Pages site (`folio-staging.yml`, e.g. litlfred/smart-ra) is
 * railed with the platform's graphs and harnesses, but those are published on
 * the PLATFORM's site: re-based against the folio page's own root, every one
 * of them 404s. `platformBase` re-bases them against the platform's published
 * root instead, while the home row stays the folio's own root.
 */
export interface ForeignSiteRail {
  /** The platform site's root, no trailing slash: `https://litlfred.github.io/folio-assistant`. */
  platformBase: string;
  /** What the home row is called — the folio's name, not the platform's. */
  homeLabel?: string;
  /**
   * The layer whose OWN site this is — an IG repository that instantiates
   * a harness and builds its own site (bean `mftp`, owner 2026-10-05:
   * "harnesses in bottom LHS navbar link back to folio-assist, not
   * smart-immz"). Given, the navbar is that layer's: its name and mark in
   * the header, its graphs, and a Harnesses list of IT and the harnesses it
   * is built on (its `needs`, transitively) — itself linking to this site's
   * root, the others to their own pages. Absent, the rail is the platform's.
   */
  instance?: string;
  /**
   * `instance` is only the harness the site LANDS on, not the site's owner:
   * the checkout declares no instance of its own (an IG repository whose
   * `index.config.json` names `site.landing` and nothing else — the
   * `build-instance-site.ts` identity route). Then the rail is the SITE's:
   * its title in the header, a Graphs group of only the landing's graphs this
   * site holds (linked within it), and a Harnesses list of the site itself,
   * linking to its root, followed by the landing and what it is built on,
   * each linking to its own page on the platform's site. The landing's other
   * graphs are not this site's, and stay reachable from the landing's row.
   * Owner, 2026-10-14, on one content IG (paraphrased): its active graphs had
   * broken links that went back to the base IG it builds on, not to itself.
   */
  landing?: boolean;
}

/**
 * A layer and the harnesses it is built on, as navbar rows: the layer
 * first, linking to `ownHref`, then every harness reachable through `needs`,
 * in `harness.json`'s order, each linking to its own page re-based on
 * `linkRoot`. A harness with no page is listed without a link rather than
 * dropped. Undefined when `harness.json` cannot be read.
 */
export function instanceHarnesses(
  built: string,
  instance: string,
  linkRoot: string,
  /** Where the layer's row links; `undefined` links it to its own page on `linkRoot`, as the others. */
  ownHref: string | undefined,
  /** Where the layer's OWN mark resolves; default `linkRoot`. See {@link ownsCheckout}. */
  ownMarkRoot: string = linkRoot,
): NavItem[] | undefined {
  const prefix = publishedDocsPrefix(REPO, built);
  if (prefix === undefined) return undefined;
  const data = join(REPO, prefix, "_data", "harness.json");
  if (!existsSync(data)) return undefined;
  let d: { harnesses?: { name?: string; label?: string; title?: string; href?: string | null; tone?: number; mark?: HarnessMark | null; needs?: string[] }[] };
  try {
    d = JSON.parse(readFileSync(data, "utf-8"));
  } catch {
    return undefined;
  }
  const rows = d.harnesses ?? [];
  const byName = new Map(rows.map((h) => [h.name, h]));
  const reach = new Set<string>([instance]);
  for (const queue = [instance]; queue.length > 0; ) {
    for (const n of byName.get(queue.shift()!)?.needs ?? []) {
      if (reach.has(n)) continue;
      reach.add(n);
      queue.push(n);
    }
  }
  return rows
    .filter((h) => h.name !== undefined && reach.has(h.name))
    .sort((a, b) => (a.name === instance ? -1 : b.name === instance ? 1 : 0))
    .map((h) => {
      const label = h.label ?? h.title ?? h.name ?? "?";
      const href = h.name === instance && ownHref !== undefined ? ownHref : h.href ? `${linkRoot}${h.href}` : undefined;
      const markRoot = h.name === instance ? ownMarkRoot : linkRoot;
      return { label, ...(href ? { href } : {}), ...navMarkFields(h.mark, h.tone, (src) => `${markRoot}${src}`) };
    });
}

/**
 * Is `instance` the root of the checkout this rail is built from — the folio
 * whose OWN site this is, with its harness data generated from it?
 *
 * Then its mark is a path on its own site, not the platform's (issue #46, gap
 * 4): `harness-tiles.ts` places the root layer's declared icon at `/` +
 * its path under its site directory (`siteDirMount`), and composed against
 * the platform's address it 404'd on the folio's site. The same rule
 * `rootOwnPages` applies to the folio's pages.
 */
export function ownsCheckout(instance: string | undefined): boolean {
  return instance !== undefined && readDeclaration(REPO)?.name === instance;
}

/**
 * Where a layer's declaration lives: `<checkout>/<name>/` for a mounted
 * layer, and the checkout itself for the folio whose own site this is
 * ({@link ownsCheckout}). Looking only under `<checkout>/<name>/` found no
 * declaration for smart-ra's `dpi-h-ra` — declared at the repository root —
 * so every page of that site carried an EMPTY "Graphs" group (owner,
 * 2026-10-14: "graphs dont work there is nothing there").
 */
export function instanceDirOf(instance: string): string {
  return ownsCheckout(instance) ? REPO : join(REPO, instance);
}

/**
 * The folio's OWN graphs on its own site, for a page of that site.
 *
 * `harness.json`'s paths are site-absolute and name the PLATFORM's handler
 * viewers (`/en/cat-harness/beans/`); composed against the platform they open
 * the platform's work, not the folio's, and composed against this site most
 * of them do not exist. So a row links only to a page this finished site
 * HOLDS — the handler's path when the folio published it, else the
 * directory's declared `coverage.visualiser` (`en/dpi-h-ra/archimate/`) —
 * and otherwise stays an unlinked row saying why.
 */
export function ownSiteGraphs(
  siteAbs: string,
  built: string,
  instance: string,
  toRoot: string,
): Map<string, GraphFallback> {
  const held = (p: string): string | undefined => {
    const rel = p.replace(/^\/+/, "");
    if (rel.endsWith(".html")) return existsSync(join(siteAbs, rel)) ? rel.replace(/(^|\/)index\.html$/, "$1") : undefined;
    const dirRel = rel === "" || rel.endsWith("/") ? rel : `${rel}/`;
    return existsSync(join(siteAbs, dirRel, "index.html")) ? dirRel : undefined;
  };
  const declared = new Map<string, string>();
  try {
    for (const entry of instanceDirectories(REPO) as { id: string; graphTypologies?: string[]; coverage?: Parameters<typeof visualisationsOf>[0] }[]) {
      for (const v of visualisationsOf(entry.coverage, entry.id)) {
        const at = held(v.ref);
        if (at === undefined) continue;
        for (const kind of entry.graphTypologies ?? []) if (!declared.has(kind)) declared.set(kind, at);
      }
    }
  } catch {
    // An unparseable declaration is `kg:schema:check`'s finding; the rows still come from `declaredGraphs`.
  }
  const out = new Map<string, GraphFallback>();
  for (const [kind, f] of publishedGraphs(built, instance, "")) {
    const { href, note: _note, ...named } = f;
    // `harness.json` names the platform's routes: the folio's own pages are under
    // `/<instance>/` there and at this site's root here (`/<instance>/catalogue/` is
    // the layer's own `/catalogue/`). Scoped the way compose-docs scopes the shell's
    // copy of the same file (`siteHref`), so the rail and the sidebar agree.
    const scopedHref = href !== undefined ? siteHref(href, { instance, platformBase: PLATFORM_BASE }) : undefined;
    const at = (href !== undefined ? (held(href) ?? (scopedHref !== href ? held(scopedHref!) : undefined)) : undefined) ?? declared.get(kind);
    if (at !== undefined) out.set(kind, { href: `${toRoot}/${at}`, ...named });
    else out.set(kind, { note: f.note ?? "not published on this site", ...named });
  }
  for (const [kind, at] of declared) if (!out.has(kind)) out.set(kind, { href: `${toRoot}/${at}` });
  return out;
}

/**
 * The landing's graphs that a site whose checkout declares no layer HOLDS
 * ({@link ForeignSiteRail.landing}), by kind, each href relative to the site
 * root. Every other graph of the landing is published on the platform's site,
 * not this one, and is left out rather than listed as this site's.
 */
export function landedSiteGraphs(siteAbs: string, built: string, landing: string): Map<string, GraphFallback> {
  const out = new Map<string, GraphFallback>();
  for (const [kind, f] of publishedGraphs(built, landing, "")) {
    if (f.href === undefined) continue;
    const rel = f.href.replace(/^\/+/, "");
    const page = rel.endsWith(".html") ? rel : `${rel === "" || rel.endsWith("/") ? rel : `${rel}/`}index.html`;
    if (existsSync(join(siteAbs, page))) out.set(kind, { ...f, href: rel });
  }
  return out;
}

export function railStandalonePages(
  siteAbs: string,
  built: string,
  instanceName: string,
  mountRoutes: readonly string[],
  foreign?: ForeignSiteRail,
  opts: RailPassOptions = {},
): { injected: number; alreadyNavigated: number; redirects: number; declined: number; skipped: string[]; replacedThemeSidebar: number; finished: number; pinned?: ReturnType<typeof pinPlatformChrome> } {
  const skipped: string[] = [];
  let injected = 0;
  let alreadyNavigated = 0;
  let redirects = 0;
  let declined = 0;
  let replacedThemeSidebar = 0;

  // ONE RAIL ON EVERY PAGE (owner, 2026-10-15, option A): given the Jekyll
  // source, the theme's own pages are railed too — their `.side-bar` is
  // replaced by the rail, whose Pages section is the same tree, built here
  // once (`lib/jekyll-pages-nav.ts`) and given to every page of the site.
  const pageTree = opts.themeSource ? jekyllNavPages(opts.themeSource) : undefined;
  // The theme's search, where the site publishes it: the top bar of a page
  // the theme did not lay out searches the same index (`lib/site-bar.ts`).
  const themeSearch = THEME_SEARCH_SCRIPTS.every((s) => existsSync(join(siteAbs, s))) ? THEME_SEARCH_SCRIPTS : undefined;
  // A page inside a layer's folio pages is railed as that layer's (#1902).
  const scopes = pageTree && !foreign ? railScopesOf(built) : [];

  const owned = (rel: string): boolean =>
    mountRoutes.some((r) => rel === r || rel.startsWith(`${r}/`)) ||
    NOT_THIS_PASS.some((r) => rel === r || rel.startsWith(`${r}/`)) ||
    rel === "STAGING" ||
    rel.startsWith("STAGING/");

  // A site whose checkout declares no layer: computed once, it is the same on every page.
  const landed = foreign?.landing === true && foreign.instance !== undefined ? landedSiteGraphs(siteAbs, built, foreign.instance) : undefined;

  const railContext = new Map<string, { named: ReturnType<typeof railNames>; linkRoot: string; links: NavItem[]; homeLabel: string | undefined; harnesses: NavItem[] | undefined; mark: ReturnType<typeof instanceMark> }>();
  const navbarRow = foreign ? rebaseNavbarRow(navbarRowData(built), foreign.platformBase, foreign.instance) : navbarRowData(built);
  // Worked out once per pass, not once per page (bean fwtz, the KG step): each
  // depends only on the key it is stored under, and at 11,842 pages the
  // per-page versions were most of the pass — `igSiteOwner` reads a declaration
  // from disk, `pagesNav` rebuilds the whole page tree, and a writer made per
  // page re-read the shared rail data file once per page.
  const emitRailData = railDataWriter(siteAbs);
  const igOwners = new Map<string, string | undefined>();
  const igOwnerOf = (segment: string): string | undefined => {
    if (!igOwners.has(segment)) igOwners.set(segment, igSiteOwner(segment));
    return igOwners.get(segment);
  };
  const pageTrees = new Map<string, NavItem[] | undefined>();
  const pagesFor = (toRoot: string, locale: string, scopeHref: string | undefined): NavItem[] | undefined => {
    if (!pageTree) return undefined;
    const key = `${toRoot}\0${locale}\0${scopeHref ?? ""}`;
    if (pageTrees.has(key)) return pageTrees.get(key);
    const treeKey = `${toRoot}\0${locale}\0`;
    let tree = pageTrees.get(treeKey);
    if (tree === undefined) pageTrees.set(treeKey, (tree = pagesNav(pageTree, { prefix: toRoot, locale }).items));
    const pages = scopeHref !== undefined ? pagesUnder(tree, `${toRoot}${scopeHref}`) : tree;
    pageTrees.set(key, pages);
    return pages;
  };
  const walk = (dir: string): void => {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      if (e.name.startsWith(".")) continue;
      const abs = join(dir, e.name);
      const rel = abs.slice(siteAbs.length + 1);
      if (e.isDirectory()) {
        if (!owned(rel)) walk(abs);
        else if (mountRoutes.some((r) => rel === r || rel.startsWith(`${r}/`))) finish(abs);
        continue;
      }
      if (!e.name.endsWith(".html") || owned(rel)) continue;

      const read = readFileSync(abs, "utf-8");
      const themed = pageTree !== undefined && hasThemeSidebar(read);
      const before = themed ? stripThemeSidebar(read) : read;
      if (NAVIGATED.test(before)) {
        alreadyNavigated++;
        // Its rail is its own, but its first paint is the site's rule: a page
        // a generator railed itself (the IRIS replica's pages, 2026-10-15)
        // carried no first-paint snippet, so it painted the static dark sheet
        // and flipped once the rail's script ran. And a railed page that also
        // wears the theme's sidebar loses the sidebar: one rail. Idempotent.
        const finished = finishRailedPage(before, false);
        if (finished !== read) {
          writeFileSync(abs, finished);
          if (themed) replacedThemeSidebar++;
        }
        continue;
      }
      // A REDIRECT STUB is not a page anybody stays on — the mount writes one
      // for a kind route whose directory is not mounted (bean `2b5s`). Railing
      // it would make a one-file redirect carry the whole navigation.
      if (REDIRECT.test(before)) {
        redirects++;
        continue;
      }
      // A page that DECLINED the rail in its own markup keeps that decision
      // here too (#1881). The generator honoured it; this post-build walk did
      // not, so every library entry shell was railed in CI only — 2.8 KB
      // committed, 25 KB published.
      if (declinesNavbar(before)) {
        declined++;
        continue;
      }
      // `..` per directory the page sits under; the filename is not one.
      const depth = rel.split("/").length - 1;
      const toRoot = depth === 0 ? "." : new Array(depth).fill("..").join("/");
      // A page of an `igSite` layer's own IG site (bean `mftp`) is THAT
      // layer's page: its name, mark and graphs, not the platform's.
      const here = `/${rel.replace(/(^|\/)index\.html$/, "$1")}`;
      const scope = scopes.find((s) => here.startsWith(s.href));
      const owner = foreign ? (foreign.instance ?? instanceName) : (igOwnerOf(rel.split("/")[0]!) ?? scope?.name ?? instanceName);
      // Everything below depends on the owner and the page's depth alone, so it
      // is worked out once per pair, not once per page: `declaredGraphs` reads
      // the declarations, and at 11,834 pages that was most of the KG step (bean fwtz).
      const ctxKey = `${owner}\0${toRoot}`;
      let ctx = railContext.get(ctxKey);
      if (ctx === undefined) {
        ctx = (() => {
          const named = railNames(built, owner);
          // The platform's links resolve against the platform's site; only home is this site's.
          const linkRoot = foreign?.platformBase ?? toRoot;
          // The folio's OWN graphs are on this site, and link only where it holds them.
          const site = landed
            ? new Map([...landed].map(([kind, f]) => [kind, { ...f, href: `${toRoot}/${f.href}` }]))
            : foreign && ownsCheckout(owner)
              ? ownSiteGraphs(siteAbs, built, owner, toRoot)
              : publishedGraphs(built, owner, linkRoot);
          const declared = declaredGraphs(owner, new Map(), site, named.harness);
          // The landing's graphs this site does not hold are the landing's, not this site's.
          const links = landed ? declared.filter((l) => l.href !== undefined) : declared;
          // The folio's OWN mark is on its own site when it is the checkout's root (gap 4).
          const markRoot = foreign && ownsCheckout(foreign.instance) ? toRoot : linkRoot;
          const homeLabel = foreign ? foreign.homeLabel : named.site;
          const listed = landed
            ? [{ label: homeLabel ?? named.harness ?? owner, href: `${toRoot}/` }, ...(instanceHarnesses(built, foreign!.instance!, linkRoot, undefined) ?? [])]
            : foreign?.instance
              ? instanceHarnesses(built, foreign.instance, linkRoot, `${toRoot}/`, markRoot)
              : instantiatedHarnesses(built, linkRoot);
          // A FHIR IG rendered on this site gets a `[fhir]` row to its index
          // page, right after its harness's row (owner, 2026-10-31).
          const harnesses = withIgRenderRow(listed, {
            siteAbs,
            owner,
            ownerLabel: landed ? (homeLabel ?? named.harness ?? owner) : named.harness,
            atRoot: foreign !== undefined || owner === instanceName,
            toRoot,
          });
          // The landing's mark is not this site's: a site with no instance of its own draws none.
          const mark = landed ? undefined : instanceMark(built, owner, foreign?.instance === owner ? markRoot : linkRoot);
          return { named, linkRoot, links, homeLabel, harnesses, mark };
        })();
        railContext.set(ctxKey, ctx);
      }
      const { named, linkRoot, links, homeLabel, harnesses, mark } = ctx;
      // The page tree, cut to the layer's own pages when the page is inside one.
      const pages = pagesFor(toRoot, pageLangOf(before), scope?.href);
      const railed = injectRailOnce(before, {
        instance: landed ? (homeLabel ?? named.harness ?? owner) : (named.harness ?? owner),
        ...(homeLabel ? { homeLabel } : {}),
        toRoot,
        // The row's files are the PLATFORM's (bean `lhvt`). On a folio's site its
        // remaining site-root hrefs and counts are the FOLIO's (issue #46, gap 2).
        assetRoot: linkRoot,
        // The rail's code and style: the site's own pinned copy on a foreign
        // site (owner, 2026-10-15), never the platform's live `assets/`.
        ...(foreign ? { rowRoot: toRoot, chromeRoot: toRoot } : {}),
        ...(mark ? { mark } : {}),
        links,
        ...(harnesses ? { harnesses } : {}),
        navbarRow,
        emitRailData,
        // A folio's site: the icon row is the same on every page, so it is
        // written once beside the rail's data rather than into each page
        // (2026-10-10 — 849 KB of 1.76 MB of railed HTML on one folio).
        ...(foreign ? { shareNavbarRow: true } : {}),
        ...(pages && pages.length ? { pages, here } : {}),
      });
      if (railed === undefined) {
        skipped.push(rel);
        continue;
      }
      // The top bar, the same on every page (owner, 2026-10-15: "Top bar, like IG sites").
      const after = withSiteBar(railed, { toRoot, title: homeLabel ?? named.site ?? named.harness ?? owner, ...(themeSearch ? { search: themeSearch } : {}) });
      writeFileSync(abs, foreign ? withPinnedData(withPlatformUi(after, toRoot, foreign.platformBase), toRoot) : withSavedScheme(after));
      if (themed) replacedThemeSidebar++;
      injected++;
    }
  };
  // THE MOUNT ROUTES, FINISHED. Their pages are the mount pass's to rail, but
  // what every railed page carries is this site's rule, checked here, last,
  // after every generator: the mount pass ran before some of them, and a
  // page it found railed by its own generator it used to leave as it was.
  let finished = 0;
  const finish = (dir: string): void => {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      if (e.name.startsWith(".")) continue;
      const abs = join(dir, e.name);
      if (e.isDirectory()) {
        finish(abs);
        continue;
      }
      if (!e.name.endsWith(".html")) continue;
      const read = readFileSync(abs, "utf-8");
      if (!hasRail(read)) continue;
      const out = finishRailedPage(read, pageTree !== undefined);
      if (out === read) continue;
      writeFileSync(abs, out);
      finished++;
    }
  };
  if (existsSync(siteAbs)) walk(siteAbs);
  // The files those pages now link, shipped with them — only when a page was railed.
  const pinned = foreign && injected > 0 ? pinPlatformChrome(siteAbs) : undefined;
  // The page layout the top bar is laid out by, beside the pages that link it.
  if (injected > 0) writePageLayout(siteAbs);
  return { injected, alreadyNavigated, redirects, declined, skipped, replacedThemeSidebar, finished, ...(pinned ? { pinned } : {}) };
}

/**
 * The layer whose own IG site is served at `/<segment>/`, when that
 * directory's declaration marks a docs directory `igSite` (bean `mftp`):
 * its IG pages are built by `stage-ig-sites`, and railed here as ITS pages.
 */
export function igSiteOwner(segment: string): string | undefined {
  if (!segment || segment.includes(".")) return undefined;
  const at = declarationPathIn(join(REPO, segment));
  if (at === undefined || !existsSync(at)) return undefined;
  try {
    const d = JSON.parse(readFileSync(at, "utf-8")) as { directories?: { igSite?: boolean }[] };
    return d.directories?.some((x) => x.igSite === true) ? segment : undefined;
  } catch {
    return undefined;
  }
}

/**
 * The routes the MOUNT pass owns, computed by the pipeline that owns them.
 *
 * `rail-standalone-pages.ts` must leave these alone, because {@link injectRails}
 * has already railed them with a PER-INSTANCE model; a second rail there would
 * carry the ROOT layer's graphs instead of the mounted layer's.
 *
 * It is derived rather than guessed, and the first version guessed. It took a
 * directory in the site to be a mount when a same-named `<name>/<name>.json`
 * existed in the repository — which is true of `bootstrap`, a layer that
 * declares no renderable docs and is therefore **never mounted**. The guess
 * excluded exactly the ten pages the pass was extended to reach.
 *
 * `mountable()` requires a rendered `index.html`, `withRoutes` assigns the
 * route and `resolve_` refuses a collision. Asking them is one answer; a
 * predicate over filenames is a second one, free to disagree.
 */
export function mountRoutes(built: string): string[] {
  const found = mountable().filter((m) => !(m.name === built && m.kind === "docs"));
  const { candidates } = withRoutes(found, igSiteRoots());
  return resolve_(candidates).mounts.map((m) => m.route);
}

/**
 * Where the mount pass publishes each KIND of one layer — `docs` →
 * `/docs/who-iris/` — read off the same `mountable()` / `withRoutes` /
 * `resolve_` the pass itself runs, for `harness-tiles.ts`.
 *
 * The navbar's Folders row for a kind links a DECLARED viewer or a page under
 * the site directory, and nothing else, so a directory the mount publishes at
 * its kind route read "no viewer yet" over a page the site served. Measured on
 * litlfred.github.io/who-iris, 2026-11-13: `docs/` (the CDN proposal among
 * it) mounted at `/docs/who-iris/` and the Docs row was inert. Asking the
 * mount's own routing is one answer; composing `/<kind>/<name>/` in the tiles
 * would be a second, free to disagree the day a sibling takes a sub-route.
 *
 * Only a kind with exactly ONE kind route is answered. Same-kind siblings that
 * each take `/<kind>/<name>/<dir>/` have no single page for the row to open,
 * and picking one would be the alphabet choosing; the instance root
 * (`/<name>/`) is the layer presenting itself, not a kind's viewer.
 *
 * @returns kind → site-absolute route, with a trailing slash
 */
export function mountedKindRoutes(repo: string, name: string): Map<string, string> {
  const { candidates } = withRoutes(mountable(repo), igSiteRoots(repo));
  const byKind = new Map<string, string[]>();
  for (const m of resolve_(candidates).mounts) {
    if (m.name !== name || !m.route.startsWith(`${m.kind}/`)) continue;
    byKind.set(m.kind, [...(byKind.get(m.kind) ?? []), m.route]);
  }
  const out = new Map<string, string>();
  for (const [kind, routes] of byKind) if (routes.length === 1) out.set(kind, `/${routes[0]}/`);
  return out;
}

