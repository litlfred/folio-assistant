#!/usr/bin/env bun
/**
 * The kinds the graph-typology TABLE names, and every name a row may carry.
 *
 * @module scripts/kind-table
 * @graphNode none — a reader over one authored table
 *
 * The one parser of the table, shared by `kind:register` (a new kind owes an
 * authored ROW, which the command reports rather than writes) and
 * `tests/graph-typology-docs.test.ts`, so the two cannot drift.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, posix, relative, sep } from "node:path";

import { BASE_GRAPH_TYPOLOGIES, GRAPH_TYPOLOGY_ALIASES, defaultGraphTypologies } from "../schemas/kg/cat-harness.js";
import { graphTypologyLayer } from "../schemas/kg/graph-typology-registry.ts";
// `folio` is registered as a load-time side effect; `glossary` is a node in the
// content layer's `typologies/` graph since folio-assistant#2598.
import "../schemas/kg/folio-graph-typology.js";
import { HARNESS_ROOT } from "./lib/roots.ts";
import { groupOf, optInRootsOf, type OptInRoot } from "../schemas/kg/opt-in-roots.ts";

/** The layer root this reader is relative to. */
export const KIND_TABLE_ROOT = join(HARNESS_ROOT);
/**
 * The page the table is published on, built at publish (cat-harness's
 * `builtAtPublish`, owner 2026-10-14: "1"). It was a region of the skill
 * `skills/kg/kg-core/directory-conventions.md`, and that made the skill a
 * pin-dependent artefact: every kind any layer in the checkout declares is
 * a row, so the committed skill went stale at each re-pin that brought a
 * layer's new kind. The skill keeps its prose and names this page.
 */
// declared-path-literal: a page BUILT AT PUBLISH (cat-harness builtAtPublish), so no committed file resolves it; kind:table writes it.
export const KIND_TABLE_DOC = "docs/cat-harness/kind-table.md";
/** The table's header row, verbatim. Renaming a column is a deliberate edit. */
export const KIND_TABLE_HEADER = "| kind | declared by | contents | renderable |";

/**
 * The kinds the table names, read from its FIRST COLUMN only.
 *
 * Located by the header row rather than by position or by a pattern over the
 * prose: the file holds two pipe-tables and this is the one whose columns say
 * what they are. Absent, or present more than once, **THROWS** — a table a
 * caller cannot find is not an empty table, and a silent pass over nothing is
 * the failure mode this exists to prevent (#266 drifted through three green
 * merges that way).
 */
export function documentedKinds(root: string = KIND_TABLE_ROOT): string[] {
  // The built page when it is there; otherwise exactly what `kind:table` would
  // write, so a gate that runs before the publish step reads the same table.
  const path = join(root, KIND_TABLE_DOC);
  const lines = (existsSync(path) ? readFileSync(path, "utf8") : renderKindPage(root)).split("\n");
  const at = lines.reduce<number[]>((acc, l, i) => (l.trim() === KIND_TABLE_HEADER ? [...acc, i] : acc), []);
  if (at.length !== 1) {
    throw new Error(
      `${KIND_TABLE_DOC}: expected exactly one graph-typology table header, found ${at.length}. ` +
        `Looked for the line: ${KIND_TABLE_HEADER}`,
    );
  }
  const out: string[] = [];
  // Skip the header and the |---|---| delimiter beneath it.
  for (let i = at[0]! + 2; i < lines.length; i++) {
    const line = lines[i]!;
    if (!line.trimStart().startsWith("|")) break;
    const first = line.split("|")[1] ?? "";
    // A cell reads `` `tools` `` or `` **`folio-assist-core`** ``; the kind is the
    // backticked token, and bold marks WHO DECLARES it in the next column.
    const kind = first.replace(/[`*]/g, "").trim();
    if (kind) out.push(kind);
  }
  return out;
}

/** Every name a table row may legitimately carry. */
export function validKinds(): Set<string> {
  return new Set([
    ...defaultGraphTypologies.names(),
    ...Object.keys(BASE_GRAPH_TYPOLOGIES),
    // A deprecated alias still reads, so documenting one is not an error.
    ...Object.keys(GRAPH_TYPOLOGY_ALIASES),
  ]);
}

// ── The table is GENERATED (bean dmx1) ──────────────────────────────────────
//
// Owner, 2026-10-04: no central registry for subgraph types, and, asked what
// to do with this hand-kept table, "prose onto the nodes" (option 1 of 3): each
// row's `contents` moved onto its kind as `description` (a kind node's field,
// or a listed kind's entry), and the table is rendered from the kinds, grouped
// by who declares them. A row cannot drift from its kind, because it IS the kind.

export const KIND_TABLE_BEGIN = "<!-- kind-table:begin (generated by `bun run cat kind:table` from the declared kinds; edit the kind, not this table) -->";
export const KIND_TABLE_END = "<!-- kind-table:end -->";

/** The `declared by` cell: the owning harness for a declared kind, the layer for a listed one. */
function declaredByCell(kind: string, root: string): string {
  const file = defaultGraphTypologies.declaredBy(kind);
  if (file !== undefined) {
    const rel = relative(dirname(root), file).split(sep);
    const at = rel.indexOf("typologies");
    return `**${rel.slice(0, at).join("/")}** (\`typologies/${rel.slice(at + 1).join("/")}\`)`;
  }
  const def = defaultGraphTypologies.get(kind);
  return `**${graphTypologyLayer(kind, def)}**${def?.anyLayer ? ", and any layer" : ""}`;
}

/**
 * Where a kind description's relative links are written FROM. The table was a
 * region of the skill `skills/kg/kg-core/directory-conventions.md`, and the
 * descriptions still link as that skill would (cat-harness-tools c751864).
 */
// declared-path-literal: the directory kind descriptions' links are written relative to; only joined into a link, never read
export const KIND_LINK_BASE = "skills/kg/kg-core";

/**
 * A description's relative Markdown links, rebased from {@link KIND_LINK_BASE}
 * to the page the table is written to ({@link KIND_TABLE_DOC}), so each names
 * the same file from there. An absolute URL, a site-rooted path and an anchor
 * are left as they are.
 */
export function rebaseKindLinks(text: string, to: string = posix.dirname(KIND_TABLE_DOC)): string {
  return text.replace(/\]\(([^)\s]+)\)/g, (whole, target: string) => {
    if (/^(?:[a-z][a-z0-9+.-]*:|#|\/)/i.test(target)) return whole;
    const hash = target.indexOf("#");
    const path = hash === -1 ? target : target.slice(0, hash);
    const frag = hash === -1 ? "" : target.slice(hash);
    return `](${posix.relative(to, posix.join(KIND_LINK_BASE, path))}${frag})`;
  });
}

/**
 * A description's links into an OPT-IN sub-graph of the harness (`sdlc`,
 * `work-plan`, ...), written as their text alone. The table is an always-on
 * page and the sub-graph is absent wherever it is switched off, so such a
 * link is dead there (`check:optin-links`, cat-harness main 65a51c0: five
 * links into `cat-harness.sdlc` and `cat-harness.work-plan`). The same rule
 * as a generated list that names what is inside one without linking it
 * (`readme:sync`). Links are read relative to {@link KIND_LINK_BASE} under
 * `root`, before they are rebased.
 */
export function unlinkOptIn(text: string, root: string, roots: readonly OptInRoot[] = optInRootsOf(root)): string {
  if (roots.length === 0) return text;
  return text.replace(/\[([^\]]*)\]\(([^)\s]+)\)/g, (whole, label: string, target: string) => {
    if (/^(?:[a-z][a-z0-9+.-]*:|#|\/)/i.test(target)) return whole;
    const path = decodeURI(target.split("#")[0]!.split("?")[0]!);
    if (path === "") return whole;
    const abs = join(root, KIND_LINK_BASE, path).replace(/[\\/]+$/, "");
    return groupOf(abs, roots) === undefined ? whole : label;
  });
}

/** The table, header to last row, from the registry: bootstrap, harness, core, then each declaring harness. */
export function renderKindTable(root: string = KIND_TABLE_ROOT): string {
  const names = defaultGraphTypologies.names();
  const group = (k: string): string => {
    const file = defaultGraphTypologies.declaredBy(k);
    if (file !== undefined) return `4 ${relative(dirname(root), file)}`;
    return { bootstrap: "1", harness: "2", core: "3" }[graphTypologyLayer(k, defaultGraphTypologies.get(k))];
  };
  const ordered = names
    .map((k, i) => ({ k, i, g: group(k) }))
    .sort((a, b) => (a.g === b.g ? a.i - b.i : a.g < b.g ? -1 : 1))
    .map((x) => x.k);
  const optIn = optInRootsOf(root);
  const rows = ordered.map((k) => {
    const d = defaultGraphTypologies.get(k)!;
    // Escape a bare pipe; one already escaped in the prose stays as it is.
    const contents = rebaseKindLinks(unlinkOptIn(d.description ?? d.summary, root, optIn)).replace(/(?<!\\)\|/g, "\\|");
    const rendered = `${d.renderable ? "**yes**" : "no"}${d.renderableNote ? ` — ${d.renderableNote}` : ""}`;
    return `| \`${k}\` | ${declaredByCell(k, root)} | ${contents} | ${rendered} |`;
  });
  return [KIND_TABLE_HEADER, "|---|---|---|---|", ...rows].join("\n");
}

/** The whole published page: front matter, where it comes from, and the table. */
export function renderKindPage(root: string = KIND_TABLE_ROOT): string {
  return [
    "---",
    "layout: default",
    "title: Graph typologies",
    "lang: en",
    'description: "Every kind of directory an instance in this checkout may declare: who declares it, what it holds, and whether it renders."',
    "permalink: /cat-harness/kind-table/",
    "---",
    "",
    KIND_TABLE_BEGIN,
    "",
    "# Graph typologies",
    "",
    "Every kind of directory an instance in this checkout may declare, grouped by who declares it: bootstrap, the harness, core, then each harness that declares its own. " +
      "A row is its kind's `description`, so edit the kind, not this page. " +
      "How to declare a directory of one is the skill `directory-conventions`.",
    "",
    // A BLANK LINE each side of the table. Without one, kramdown reads the
    // table as part of the marker comment's HTML block and publishes its rows
    // as pipes (`check:escaped-markup` caught it on the built skill page).
    renderKindTable(root),
    "",
    KIND_TABLE_END,
    "",
  ].join("\n");
}

/** Write the page, or (`check`) say whether the written page is current. */
export function writeKindTable(check: boolean, root: string = KIND_TABLE_ROOT): boolean {
  const path = join(root, KIND_TABLE_DOC);
  const next = renderKindPage(root);
  if (existsSync(path) && readFileSync(path, "utf8") === next) return true;
  if (!check) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, next);
  }
  return false;
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  const current = writeKindTable(check);
  if (check && !current) {
    console.error(`✗ ${KIND_TABLE_DOC}: the kind table is stale. Run \`bun run cat kind:table\`; edit the KIND, not the table.`);
    process.exit(1);
  }
  console.log(current ? `✓ ${KIND_TABLE_DOC}: the kind table is current` : `wrote the kind table in ${KIND_TABLE_DOC}`);
}
