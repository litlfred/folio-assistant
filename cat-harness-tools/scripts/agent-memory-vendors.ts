/**
 * Per-agent definition files for the other agent hosts, each carrying the
 * same memory as Claude's.
 *
 * @module scripts/agent-memory-vendors
 * @covers memory
 *
 * Only Claude Code has per-agent memory (`memory: project` injects
 * `.claude/agent-memory/<agent>/MEMORY.md`). The other hosts have per-agent
 * definition files whose body is the prompt, so each is written whole: the
 * Claude definition's prompt (`.claude/agents/<agent>.md`), then the memory
 * nodes inline. Nothing is imported, since imports are not portable.
 *
 * ## The formats
 *
 * | host | file | front matter / keys | prompt | limit |
 * |---|---|---|---|---|
 * | Gemini CLI | `.gemini/agents/<agent>.md` | `name`, `description` required; `tools` optional (inherits all if omitted) | the Markdown body | none stated |
 * | OpenAI Codex | `.codex/agents/<agent>.toml` | `name`, `description`, `developer_instructions` required | `developer_instructions` | none stated |
 * | Cursor | `.cursor/agents/<agent>.md` | all optional: `name`, `description`, `model`, `readonly`, `is_background` | the Markdown body | none stated |
 * | GitHub Copilot | `.github/agents/<agent>.agent.md` | `description` required; `name`, `tools` optional | the Markdown body | 30,000 characters |
 *
 * Sources: geminicli.com/docs/core/subagents, learn.chatgpt.com/docs/agent-configuration/subagents,
 * cursor.com/docs/context/subagents, docs.github.com/en/copilot/reference/custom-agents-configuration
 * and docs.github.com/en/copilot/how-tos/copilot-cli/customize-copilot/create-custom-agents-for-cli.
 *
 * Cursor also reads `.claude/agents/` and `.codex/agents/`, but `.cursor/`
 * wins on a name clash, and the Claude copy carries no memory.
 *
 * ## Tools
 *
 * A Claude agent's `tools:` list is translated where the host has a
 * documented equivalent (Gemini tool names, Copilot aliases, Cursor's
 * `readonly`). A Claude tool with no equivalent (e.g. `ToolSearch`) is left
 * out, not guessed. Codex cannot restrict tools beyond feature switches, so
 * a Codex agent without `Bash` gets `features.shell_tool = false` only.
 *
 * ## Budgets
 *
 * Copilot's limit is 30,000 characters; the other three get the harness's
 * 32 KiB cap, the same as the repo-wide `AGENTS.md` section. Over budget, the
 * lowest-priority nodes are dropped and reported (never silent truncation),
 * as for the Antigravity targets.
 */

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

import { parseFrontMatter } from "../schemas/kg/front-matter.js";
import { MEMORY_LABELS, memoryForAgent, type MemoryNode } from "../schemas/conduct/memory.js";

import {
  COPILOT_AGENT_CHAR_BUDGET,
  DEFAULT_ROOT,
  VENDOR_AGENT_BYTE_BUDGET,
  agentNames,
  detailFileName,
  lowestPriorityFirst,
  readMemoryNodes,
  rebaseRuleLinks,
} from "./agent-memory.ts";

export { COPILOT_AGENT_CHAR_BUDGET, VENDOR_AGENT_BYTE_BUDGET };

/** Where Claude's agent definitions live — the source of each prompt. */
export const CLAUDE_AGENTS_DIR = join(DEFAULT_ROOT, ".claude", "agents");


/** Marks a file as generated, so a stale one can be removed safely. */
export const VENDOR_GENERATED_MARK = "Generated by `bun run cat agent-memory`";

export type VendorId = "gemini" | "codex" | "cursor" | "copilot";

export interface ClaudeAgentDef {
  name: string;
  description: string;
  tools: string[] | undefined;
  prompt: string;
}

/** Read `.claude/agents/<agent>.md`, or `undefined` when there is none. */
export function readClaudeAgent(agent: string, dir: string = CLAUDE_AGENTS_DIR): ClaudeAgentDef | undefined {
  const path = join(dir, `${agent}.md`);
  if (!existsSync(path)) return undefined;
  const { fm, body } = parseFrontMatter(readFileSync(path, "utf8"));
  const raw = fm["tools"];
  const tools = Array.isArray(raw)
    ? (raw as unknown[]).map(String)
    : typeof raw === "string" && raw.trim() !== ""
      ? raw.split(",").map((t) => t.trim()).filter(Boolean)
      : undefined;
  return {
    name: typeof fm["name"] === "string" && fm["name"] !== "" ? (fm["name"] as string) : agent,
    description: typeof fm["description"] === "string" ? (fm["description"] as string) : "",
    tools,
    prompt: body.trim(),
  };
}

// ── Tool translation ─────────────────────────────────────────────

const GEMINI_TOOLS: Record<string, readonly string[]> = {
  Read: ["read_file", "read_many_files"],
  Grep: ["grep_search"],
  Glob: ["glob", "list_directory"],
  Bash: ["run_shell_command"],
  Edit: ["replace"],
  Write: ["write_file"],
  WebFetch: ["web_fetch"],
  WebSearch: ["google_web_search"],
};

const COPILOT_TOOLS: Record<string, string> = {
  Read: "read",
  Grep: "search",
  Glob: "search",
  Bash: "execute",
  Edit: "edit",
  Write: "edit",
  NotebookEdit: "edit",
  WebFetch: "web",
  WebSearch: "web",
  Agent: "agent",
  Task: "agent",
  TodoWrite: "todo",
};

const WRITING_TOOLS = new Set(["Edit", "Write", "NotebookEdit"]);

function translate(tools: readonly string[], map: Record<string, string | readonly string[]>): string[] {
  const out: string[] = [];
  for (const t of tools) {
    const m = map[t];
    for (const v of m === undefined ? [] : typeof m === "string" ? [m] : m) {
      if (!out.includes(v)) out.push(v);
    }
  }
  return out;
}

export function geminiTools(tools: readonly string[]): string[] {
  return translate(tools, GEMINI_TOOLS);
}

export function copilotTools(tools: readonly string[]): string[] {
  return translate(tools, COPILOT_TOOLS);
}

/** An agent that cannot write files: Cursor's `readonly: true`. */
export function isReadonly(tools: readonly string[] | undefined): boolean {
  return tools !== undefined && !tools.some((t) => WRITING_TOOLS.has(t));
}

// ── Rendering ────────────────────────────────────────────────────

/**
 * The memory section every vendor file carries. Links are rebased for a file
 * two directories below the repository root (`.<host>/agents/`), and a detail
 * pointer names the sidecar by its path from the root, since the sidecar sits
 * beside Claude's `MEMORY.md`, not beside this file.
 */
export function renderVendorMemory(agent: string, entries: readonly MemoryNode[], root?: string): string {
  if (entries.length === 0) return "";
  const rank = (m: MemoryNode): number => MEMORY_LABELS.indexOf(m.label);
  const sorted = [...entries].sort((a, b) => rank(a) - rank(b) || a.id.localeCompare(b.id));
  const items = sorted.map((m) => {
    const head = `### ${m.label.toUpperCase()} — ${m.summary}`;
    const meas = m.measured
      ? `\n\n> Measured \`${m.measured.command}\` on ${m.measured.date}: ${m.measured.result}`
      : "";
    const more = m.detail ? `\n\nMore: \`.claude/agent-memory/${agent}/detail/${detailFileName(m.id)}\`` : "";
    return `${head}\n\n${rebaseRuleLinks(m.comment, root)}${meas}${more}`;
  });
  return (
    `## Memory\n\n` +
    `Lessons this agent has already paid for here. Types: **STABLE** (true), ` +
    `**TRAP** (what goes wrong), **BASELINE** (a measurement: re-measure, never quote).\n\n` +
    items.join("\n\n")
  );
}

function generatedNote(prefix: string, suffix = ""): string {
  return (
    `${prefix}${VENDOR_GENERATED_MARK} from .claude/agents/ and every declared ` +
    `\`memory\` directory (bean 31ni). Do not edit: change those and regenerate.${suffix}`
  );
}

function promptWithMemory(def: ClaudeAgentDef, memory: string): string {
  return memory === "" ? def.prompt : `${def.prompt}\n\n${memory}`;
}

function yamlList(items: readonly string[]): string {
  return `[${items.map((t) => JSON.stringify(t)).join(", ")}]`;
}

export function renderGeminiAgent(def: ClaudeAgentDef, memory: string): string {
  const fm = [`name: ${def.name}`, `description: ${JSON.stringify(def.description)}`];
  if (def.tools !== undefined) fm.push(`tools: ${yamlList(geminiTools(def.tools))}`);
  return (
    `---\n${fm.join("\n")}\n---\n\n` +
    `${generatedNote("<!-- ", " -->")}\n\n` +
    `${promptWithMemory(def, memory)}\n`
  );
}

export function renderCursorAgent(def: ClaudeAgentDef, memory: string): string {
  const fm = [`name: ${def.name}`, `description: ${JSON.stringify(def.description)}`, `model: inherit`];
  if (isReadonly(def.tools)) fm.push(`readonly: true`);
  return (
    `---\n${fm.join("\n")}\n---\n\n` +
    `${generatedNote("<!-- ", " -->")}\n\n` +
    `${promptWithMemory(def, memory)}\n`
  );
}

export function renderCopilotAgent(def: ClaudeAgentDef, memory: string): string {
  const fm = [`name: ${def.name}`, `description: ${JSON.stringify(def.description)}`];
  if (def.tools !== undefined) fm.push(`tools: ${yamlList(copilotTools(def.tools))}`);
  return (
    `---\n${fm.join("\n")}\n---\n\n` +
    `${generatedNote("<!-- ", " -->")}\n\n` +
    `${promptWithMemory(def, memory)}\n`
  );
}

/** A TOML basic string: always safe, whatever the prompt holds. */
export function tomlString(s: string): string {
  let out = '"';
  for (const ch of s) {
    const c = ch.codePointAt(0)!;
    if (ch === '"') out += '\\"';
    else if (ch === "\\") out += "\\\\";
    else if (ch === "\n") out += "\\n";
    else if (ch === "\t") out += "\\t";
    else if (ch === "\r") out += "\\r";
    else if (c < 0x20 || c === 0x7f) out += `\\u${c.toString(16).padStart(4, "0")}`;
    else out += ch;
  }
  return `${out}"`;
}

/**
 * A TOML multi-line literal string when the text allows one (readable in a
 * diff), else a basic string. A literal cannot hold `'''`, and a trailing `'`
 * would merge into the closing delimiter.
 */
export function tomlMultiline(s: string): string {
  if (!s.includes("'''") && !s.endsWith("'") && !/[\u0000-\u0008\u000b-\u001f\u007f]/.test(s)) {
    return `'''\n${s}\n'''`;
  }
  return tomlString(s);
}

export function renderCodexAgent(def: ClaudeAgentDef, memory: string): string {
  const lines = [
    `# ${generatedNote("")}`,
    `name = ${tomlString(def.name)}`,
    `description = ${tomlString(def.description)}`,
    `developer_instructions = ${tomlMultiline(promptWithMemory(def, memory))}`,
  ];
  if (def.tools !== undefined && !def.tools.includes("Bash")) {
    lines.push("", "[features]", "shell_tool = false");
  }
  return `${lines.join("\n")}\n`;
}

export interface VendorTargetDef {
  id: VendorId;
  vendor: string;
  dir: string;
  fileName: (agent: string) => string;
  render: (def: ClaudeAgentDef, memory: string) => string;
  /** How the budget is measured, and against what. */
  budget: { unit: "bytes" | "chars"; limit: number };
}

export function vendorTargetsFor(rootDir: string = DEFAULT_ROOT): VendorTargetDef[] {
  return [
    {
      id: "gemini",
      vendor: "Gemini CLI",
      dir: join(rootDir, ".gemini", "agents"),
      fileName: (a) => `${a}.md`,
      render: renderGeminiAgent,
      budget: { unit: "bytes", limit: VENDOR_AGENT_BYTE_BUDGET },
    },
    {
      id: "codex",
      vendor: "OpenAI Codex",
      dir: join(rootDir, ".codex", "agents"),
      fileName: (a) => `${a}.toml`,
      render: renderCodexAgent,
      budget: { unit: "bytes", limit: VENDOR_AGENT_BYTE_BUDGET },
    },
    {
      id: "cursor",
      vendor: "Cursor",
      dir: join(rootDir, ".cursor", "agents"),
      fileName: (a) => `${a}.md`,
      render: renderCursorAgent,
      budget: { unit: "bytes", limit: VENDOR_AGENT_BYTE_BUDGET },
    },
    {
      id: "copilot",
      vendor: "GitHub Copilot",
      dir: join(rootDir, ".github", "agents"),
      fileName: (a) => `${a}.agent.md`,
      render: renderCopilotAgent,
      budget: { unit: "chars", limit: COPILOT_AGENT_CHAR_BUDGET },
    },
  ];
}

export const VENDOR_TARGETS: readonly VendorTargetDef[] = vendorTargetsFor(DEFAULT_ROOT);

function measure(text: string, unit: "bytes" | "chars"): number {
  return unit === "bytes" ? Buffer.byteLength(text, "utf8") : [...text].length;
}

export interface RenderVendorAgentResult {
  content: string;
  dropped: MemoryNode[];
  size: number;
}

/**
 * Render one agent's file for one host within its budget. Copilot's limit is
 * on the prompt, so only the prompt is measured there; the others measure the
 * whole file.
 */
export function renderVendorAgent(
  target: Pick<VendorTargetDef, "render" | "budget">,
  agent: string,
  def: ClaudeAgentDef,
  entries: readonly MemoryNode[],
  root?: string,
): RenderVendorAgentResult {
  const live = entries.filter((n) => !n.archived);
  const promptOnly = target.render === renderCopilotAgent;
  const sizeOf = (active: readonly MemoryNode[]): { content: string; size: number } => {
    const memory = renderVendorMemory(agent, active, root);
    const content = target.render(def, memory);
    return { content, size: measure(promptOnly ? promptWithMemory(def, memory) : content, target.budget.unit) };
  };
  // Drop lowest priority first until the file fits; never cut an entry.
  let active = [...live];
  const dropped: MemoryNode[] = [];
  const candidates = lowestPriorityFirst(live);
  let r = sizeOf(active);
  while (r.size > target.budget.limit && candidates.length > 0) {
    const d = candidates.shift()!;
    dropped.push(d);
    active = active.filter((n) => n.id !== d.id);
    r = sizeOf(active);
  }
  const { content, size } = r;
  return { content, dropped, size };
}

export interface VendorAgentResult {
  target: VendorId;
  agent: string;
  path: string;
  state: "written" | "unchanged" | "no-definition";
  entries: number;
  dropped: MemoryNode[];
  size: number;
}

/**
 * Write every agent's file for every host. An agent with a memory directory
 * but no `.claude/agents/<agent>.md` has no prompt to carry, and is reported
 * `no-definition` rather than given a file of memory alone. A generated file
 * whose agent is gone is removed, as the Antigravity skills are; a hand-written
 * file (one without the generated mark) is never touched.
 */
export function syncVendorAgents(
  write: boolean,
  nodes: readonly MemoryNode[] = readMemoryNodes(),
  opts: {
    agents?: readonly string[];
    claudeAgentsDir?: string;
    targets?: readonly VendorTargetDef[];
  } = {},
): VendorAgentResult[] {
  const agents = opts.agents ?? agentNames();
  const targets = opts.targets ?? VENDOR_TARGETS;
  const out: VendorAgentResult[] = [];
  for (const target of targets) {
    const targetRoot = resolve(target.dir, "../..");
    const wanted = new Set<string>();
    for (const agent of agents) {
      const path = join(target.dir, target.fileName(agent));
      const def = readClaudeAgent(agent, opts.claudeAgentsDir);
      if (def === undefined) {
        out.push({ target: target.id, agent, path, state: "no-definition", entries: 0, dropped: [], size: 0 });
        continue;
      }
      wanted.add(target.fileName(agent));
      const entries = memoryForAgent([...nodes], agent);
      const { content, dropped, size } = renderVendorAgent(target, agent, def, entries, targetRoot);
      const kept = entries.filter((n) => !n.archived).length - dropped.length;
      const current = existsSync(path) ? readFileSync(path, "utf8") : undefined;
      if (current === content) {
        out.push({ target: target.id, agent, path, state: "unchanged", entries: kept, dropped, size });
        continue;
      }
      if (write) {
        mkdirSync(dirname(path), { recursive: true });
        writeFileSync(path, content);
      }
      out.push({ target: target.id, agent, path, state: "written", entries: kept, dropped, size });
    }
    if (write && existsSync(target.dir)) {
      for (const f of readdirSync(target.dir)) {
        if (wanted.has(f)) continue;
        const p = join(target.dir, f);
        const text = readFileSync(p, "utf8");
        if (text.includes(VENDOR_GENERATED_MARK) && text.includes("bean 31ni")) rmSync(p);
      }
    }
  }
  return out;
}
