/** check:generated-writers (folio-assistant#1254): all four markers read, writers derived, warn only. */
import { afterAll, describe, expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { judge, markerOf, unmarkedWrites, writersNamed } from "../check-generated-writers.ts";

const REG = new Set(["folio-library-index/v1"]);

describe("markerOf: the four markers", () => {
  test("a top-level _generated, in any position", () => {
    expect(markerOf("a.json", JSON.stringify({ $schema: "x", _generated: "scripts/gen.ts — do not hand-edit" }), REG)).toEqual({ kind: "_generated", text: "scripts/gen.ts — do not hand-edit" });
  });
  test("a $schema the registry flags generated", () => {
    expect(markerOf("a.json", JSON.stringify({ $schema: "folio-library-index/v1" }), REG)).toEqual({ kind: "registry" });
  });
  test("generated: front matter", () => {
    expect(markerOf("a.md", "---\ntitle: X\ngenerated: scripts/gen-docs-pages.ts — do not hand-edit\n---\nbody", REG)?.kind).toBe("front-matter");
  });
  test("an HTML banner", () => {
    expect(markerOf("a.md", "<!-- Generated by scripts/prov-qaqc.ts. Do not hand-edit. -->\n# P", REG)?.kind).toBe("html-banner");
  });
  test("a file that only MENTIONS generation deeper in is not marked", () => {
    expect(markerOf("a.json", JSON.stringify({ fields: { _generated: "x" } }), REG)).toBeUndefined();
    expect(markerOf("a.md", "# Title\n\nThis page is not generated.", REG)).toBeUndefined();
  });
});

describe("writersNamed", () => {
  test("script paths and bun run cat tasks", () => {
    expect(writersNamed("folio-assistant-core/scripts/glossary-page.ts — do not hand-edit; run `bun run cat glossary:page`")).toEqual({
      paths: ["folio-assistant-core/scripts/glossary-page.ts"],
      tasks: ["glossary:page"],
    });
  });
});

describe("judge: a writer is real when the checkout can find it", () => {
  const repo = mkdtempSync(join(tmpdir(), "gen-writers-"));
  afterAll(() => rmSync(repo, { recursive: true, force: true }));
  mkdirSync(join(repo, "tools", "scripts"), { recursive: true });
  writeFileSync(join(repo, "tools", "scripts", "gen.ts"), "");
  mkdirSync(join(repo, "content", "docs"), { recursive: true });
  const file = join(repo, "content", "docs", "page.md");
  const o = { repo, roots: [join(repo, "tools"), join(repo, "content")], tasks: new Set(["docs:pages"]) };

  test("a path found from an instance root, or a known task, passes", () => {
    expect(judge(file, { kind: "front-matter", text: "scripts/gen.ts — do not hand-edit" }, o)).toBeUndefined();
    expect(judge(file, { kind: "front-matter", text: "run `bun run cat docs:pages`" }, o)).toBeUndefined();
    expect(judge(file, { kind: "registry" }, o)).toBeUndefined();
  });
  test("a writer that moved away is a warning naming it", () => {
    expect(judge(file, { kind: "html-banner", text: "Generated by content/scripts/gen.ts" }, o)).toMatch(/does not have: content\/scripts\/gen\.ts/);
  });
  test("a marker naming no writer is a warning", () => {
    expect(judge(file, { kind: "_generated", text: "do not hand-edit" }, o)).toMatch(/names no writer/);
  });
});

describe("unmarkedWrites: a writer's declared files must carry a marker (cat-harness#693)", () => {
  const root = mkdtempSync(join(tmpdir(), "gen-writes-"));
  afterAll(() => rmSync(root, { recursive: true, force: true }));
  const content = join(root, "content");
  mkdirSync(join(content, "docs"), { recursive: true });
  writeFileSync(join(content, "docs", "marked.md"), "---\ngenerated: scripts/gen.ts\n---\n");
  writeFileSync(join(content, "docs", "bare.md"), "# no marker\n");
  const o = { repo: root, byName: new Map([["content", content]]), registry: REG };

  test("an unmarked file a glob matches is a warning; a marked one is not", () => {
    const f = unmarkedWrites([{ task: "docs:gen", instance: join(root, "tools"), globs: ["content:docs/*.md"] }], o);
    expect(f.map((x) => x.file)).toEqual(["content/docs/bare.md"]);
    expect(f[0]!.problem).toMatch(/written by `docs:gen`.*no generated marker/);
  });
  test("a glob matching nothing, or naming an absent instance, is reported", () => {
    expect(unmarkedWrites([{ task: "t", instance: content, globs: ["gone/*.md"] }], o)[0]!.problem).toMatch(/match no file/);
    expect(unmarkedWrites([{ task: "t", instance: content, globs: ["elsewhere:x.md"] }], o)[0]!.problem).toMatch(/not in this checkout/);
  });
});
