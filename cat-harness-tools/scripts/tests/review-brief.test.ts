/**
 * The review page's "What to expect" pane (cat-harness-tools#1153): what it
 * takes from a PR body, for change-set PRs and ordinary feature branches alike.
 */
import { describe, expect, test } from "bun:test";

import { briefBlocks, briefModel, briefRepo, briefText, closedIssue, whereToLook } from "../review-brief.js";
import { reviewPageHtml } from "../gen-review-page.js";

const FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code/session_x)_\n";

describe("review brief", () => {
  test("a marked review-brief section is shown alone", () => {
    const body = "intro\n<!-- review-brief -->\n**Overall:** fine.\n- No. 1: Accepted.\n<!-- /review-brief -->\nmore" + FOOTER;
    expect(briefText(body)).toEqual({ text: "**Overall:** fine.\n- No. 1: Accepted.", marked: true });
  });

  test("an ordinary PR body loses comments, the attribution line and the footer", () => {
    const body = '<!-- claude-projects-attribution: {"github_login":"x"} -->\n_Requested by **x** · [thread](https://claude.ai)_\n\nFixes the banner.' + FOOTER;
    expect(briefText(body)).toEqual({ text: "Fixes the banner.", marked: false });
  });

  test("keeps a rule that is part of the body", () => {
    expect(briefText("a\n\n---\n\nb").text).toBe("a\n\n---\n\nb");
  });

  test("finds the issue a PR closes", () => {
    expect(closedIssue("Closes #184. Change set CS-001.")).toBe(184);
    expect(closedIssue("fixes #7")).toBe(7);
    expect(closedIssue("see #9")).toBeNull();
  });

  test("names the change set only when the title does", () => {
    const pr = { number: 185, title: "CS-001: define DPI-F", body: "x", url: "https://github.com/o/r/pull/185" };
    expect(briefModel({ staging: null, pr, issue: null, source: "live" }).changeSet).toBe("CS-001");
    expect(briefModel({ staging: null, pr: { ...pr, title: "fix: banner" }, issue: null, source: "live" }).changeSet).toBeNull();
    expect(briefModel({ staging: null, pr: null, issue: null, source: "live" }).source).toBe("none");
  });

  test("reads the repository from the banner's links", () => {
    expect(briefRepo({ branchUrl: "https://github.com/litlfred/smart-ra/tree/b" })).toEqual({ owner: "litlfred", repo: "smart-ra" });
    expect(briefRepo({ branchUrl: "javascript:alert(1)" })).toBeNull();
  });

  test("where to look: sections by number of changes, most first", () => {
    const c = (s: string) => ({ head: { section: s } });
    expect(whereToLook([c("a"), c("b"), c("b"), c("c")], 2)).toEqual([{ section: "b", count: 2 }, { section: "a", count: 1 }]);
  });

  test("Markdown blocks: headings, lists, rules, paragraphs", () => {
    expect(briefBlocks("## H\n\n- one\n  more\n- two\n\npara\nline\n\n---")).toEqual([
      { type: "h", level: 2, text: "H" },
      { type: "ul", items: ["one more", "two"] },
      { type: "p", text: "para line" },
      { type: "hr" },
    ]);
  });

  test("the page carries the pane and never uses innerHTML", () => {
    const html = reviewPageHtml();
    expect(html).toContain('id="brief"');
    expect(html).toContain("var renderBrief = ");
    expect(html).toContain('get(ROOT + "review-brief.json")');
    expect(html).not.toContain("innerHTML");
    // A regex escape lost in the template would match "ddd", never "185".
    expect(html).toContain("/^\\d+$/.test(String(st.pr");
  });
});
